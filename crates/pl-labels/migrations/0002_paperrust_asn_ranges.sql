-- PaperRust: optional ASN number ranges with storage location (crate pl-labels, docs/contract/pl-labels.md §Nummernkreise).
--
-- * paperrust_asn_config: exactly one row (id = 1) with the admin switch "Multiple number ranges" and the
--   name of the user field for the storage location. If the row is missing: off, "Ablageort".
-- * paperrust_asn_range: number ranges (name, abbreviation, storage location, first/last number, note).
--   Overlaps and duplicate abbreviations are checked by the server (under an advisory lock), the database
--   secures only the basic rules.
-- * expand-only: only new tables with prefix paperrust_, no change to Django tables.
-- * idempotent (IF NOT EXISTS), may run multiple times.
-- * Rollback: DROP TABLE paperrust_asn_range; DROP TABLE paperrust_asn_config; (no upstream data affected;
--   already created user fields "Ablageort" are kept as normal user fields)

CREATE TABLE IF NOT EXISTS paperrust_asn_config (
    id                  smallint     PRIMARY KEY DEFAULT 1,
    ranges_enabled      boolean      NOT NULL DEFAULT false,
    location_field_name varchar(128) NOT NULL DEFAULT 'Ablageort',
    modified            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT paperrust_asn_config_single_chk CHECK (id = 1)
);

CREATE TABLE IF NOT EXISTS paperrust_asn_range (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(64)  NOT NULL,
    code        varchar(8)   NOT NULL,
    location    varchar(128) NOT NULL DEFAULT '',
    first_asn   bigint       NOT NULL,
    last_asn    bigint       NOT NULL,
    note        text         NOT NULL DEFAULT '',
    created     timestamptz  NOT NULL DEFAULT now(),
    modified    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT paperrust_asn_range_span_chk CHECK (first_asn >= 0 AND last_asn >= first_asn)
);
CREATE INDEX IF NOT EXISTS paperrust_asn_range_span_idx ON paperrust_asn_range (first_asn, last_asn);
CREATE UNIQUE INDEX IF NOT EXISTS paperrust_asn_range_code_uq ON paperrust_asn_range (upper(code));
