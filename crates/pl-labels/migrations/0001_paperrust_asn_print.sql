-- PaperRust: printed/reserved ASN ranges of the label generator (crate pl-labels,
-- docs/contract/pl-labels.md). This way the generator never suggests the same numbers twice and
-- warns about overlaps.
--
-- * expand-only: only a new table with prefix paperrust_, no change to Django tables.
--   FK to auth_user with ON DELETE SET NULL (ranges stay reserved even if the user leaves).
-- * idempotent (IF NOT EXISTS), may run multiple times.
-- * Rollback: DROP TABLE paperrust_asn_print; (no upstream data affected)

CREATE TABLE IF NOT EXISTS paperrust_asn_print (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_asn   bigint       NOT NULL,
    last_asn    bigint       NOT NULL,
    prefix      varchar(32)  NOT NULL,
    digits      smallint     NOT NULL,
    code_type   varchar(16)  NOT NULL,
    sheet       varchar(64)  NOT NULL,
    label_count integer      NOT NULL,
    user_id     integer      REFERENCES auth_user (id) ON DELETE SET NULL,
    created     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT paperrust_asn_print_range_chk CHECK (first_asn >= 0 AND last_asn >= first_asn)
);
CREATE INDEX IF NOT EXISTS paperrust_asn_print_range_idx ON paperrust_asn_print (first_asn, last_asn);
