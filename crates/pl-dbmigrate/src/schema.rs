//! Embedded target schema: exactly what Django (paperless-ngx v3.4.2) produces on PostgreSQL.
//!
//! Generated with `tests/dbmigrate/gen_schema.py` (upstream `manage.py migrate` against an empty
//! PostgreSQL DB, then `pg_dump --schema-only --section=pre-data|post-data`, cleaned of
//! `SET`/`set_config`/`\restrict`/comments). Do not change by hand.

use crate::value::Kind;
use std::collections::{BTreeMap, BTreeSet};

pub const VERSION: &str = "3.4.2";
pub const PRE_DATA: &str = include_str!("../schema/v3.4.2-postgres-pre.sql");
pub const POST_DATA: &str = include_str!("../schema/v3.4.2-postgres-post.sql");
const COLUMNS: &str = include_str!("../schema/v3.4.2-columns.tsv");
const MIGRATIONS: &str = include_str!("../schema/v3.4.2-migrations.tsv");
const REPLACED: &str = include_str!("../schema/v3.4.2-replaced.tsv");
const HISTORICAL: &str = include_str!("../schema/v3.4.2-historical.tsv");

/// post-data for execution: the partial index of allauth-mfa with Django's original expression
/// (`IN (…)` like `UniqueConstraint(condition=Q(type__in=…))`). The pg_dump text
/// (`= ANY ((ARRAY[…])::text[])`) would be stored differently on re-reading
/// (`ARRAY[(…)::text, …]`); this way the result is identical to upstream `migrate` (like pl-cli
/// `migrate::schema_post`).
pub fn post_data() -> String {
    fix_post(POST_DATA)
}

fn fix_post(text: &str) -> String {
    text.replace(
        "WHERE ((type)::text = ANY ((ARRAY['totp'::character varying, 'recovery_codes'::character varying])::text[]));",
        "WHERE (\"type\" IN ('totp', 'recovery_codes'));",
    )
}

/// Schema of a freshly migrated paperless-ngx **2.20.15** database (copy path for 2.x sources:
/// first copy and verify this way, then convert in place in the target to v3.4.2). Generated by
/// `tests/dbmigrate/gen_schema_v220.sh` (from `make_v220_fixture.sh`), without the tables of
/// django-celery-results (documents.0020 drops them). Do not change by hand.
pub mod v220 {
    use super::*;

    pub const VERSION: &str = "2.20.15";
    pub const PRE_DATA: &str = include_str!("../schema/v2.20-postgres-pre.sql");
    pub const POST_DATA: &str = include_str!("../schema/v2.20-postgres-post.sql");
    const COLUMNS: &str = include_str!("../schema/v2.20-columns.tsv");
    const MIGRATIONS: &str = include_str!("../schema/v2.20-migrations.tsv");

    pub fn post_data() -> String {
        fix_post(POST_DATA)
    }

    pub fn tables() -> Result<Vec<Table>, String> {
        parse_columns(COLUMNS)
    }

    /// django_migrations of a freshly migrated 2.20.15 DB (without django_celery_results).
    pub fn expected_migrations() -> BTreeSet<(String, String)> {
        pairs(MIGRATIONS, 2).into_iter().map(|v| (v[0].clone(), v[1].clone())).collect()
    }

    /// Tables of a 2.x source that are not copied: 3.0 drops them (documents.0020).
    pub fn dropped_table(name: &str) -> bool {
        name.starts_with("django_celery_results_")
    }
}

/// Migrations from paperless-ngx **after** v3.4.2 (upstream `dev`) whose effect PaperRust knows.
/// A database with them is accepted; the rows stay in django_migrations.
/// - documents.0028_replace_tag_tree_fields (#14612): removes the django-treenode columns of
///   documents_tag except tn_parent_id – exactly like PaperRust's own migration
///   `pl_objects.0001_paperrust_tag_adjacency`.
/// - documents.0029_alter_workflowrun_type_alter_workflowtrigger_type: only a new choice "Manual",
///   no database change (type smallint, nullability and CHECK unchanged).
pub const KNOWN_NEWER: &[(&str, &str)] =
    &[("documents", "0028_replace_tag_tree_fields"), ("documents", "0029_alter_workflowrun_type_alter_workflowtrigger_type")];

/// The columns of documents_tag removed by documents.0028 (or pl_objects.0001).
pub const TREENODE_DERIVED: &[&str] = &[
    "tn_ancestors_pks",
    "tn_ancestors_count",
    "tn_children_pks",
    "tn_children_count",
    "tn_depth",
    "tn_descendants_pks",
    "tn_descendants_count",
    "tn_index",
    "tn_level",
    "tn_priority",
    "tn_order",
    "tn_siblings_pks",
    "tn_siblings_count",
];

#[derive(Debug, Clone)]
pub struct Column {
    pub name: String,
    pub udt: String,
    pub max_len: Option<usize>,
    pub nullable: bool,
    pub generated: bool,
    pub pk: bool,
    pub kind: Kind,
}

#[derive(Debug, Clone)]
pub struct Table {
    pub name: String,
    /// in ordinal order
    pub columns: Vec<Column>,
}

impl Table {
    /// Columns that are copied (without GENERATED ALWAYS … STORED)
    pub fn copy_columns(&self) -> Vec<&Column> {
        self.columns.iter().filter(|c| !c.generated).collect()
    }
    #[cfg(test)]
    pub fn pk(&self) -> Option<&Column> {
        self.columns.iter().find(|c| c.pk)
    }
}

/// Tables of the schema (sorted by name).
pub fn tables() -> Result<Vec<Table>, String> {
    parse_columns(COLUMNS)
}

pub fn parse_columns(tsv: &str) -> Result<Vec<Table>, String> {
    let mut map: BTreeMap<String, Vec<(i64, Column)>> = BTreeMap::new();
    for (ln, line) in tsv.lines().enumerate() {
        let line = line.trim_end_matches('\r');
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split('\t').collect();
        if f.len() != 8 {
            return Err(format!("columns.tsv Zeile {}: 8 Felder erwartet", ln + 1));
        }
        let max_len = if f[4].is_empty() { None } else { f[4].parse().ok() };
        let kind =
            Kind::from_udt(f[3], max_len).ok_or_else(|| format!("Spaltentyp {} ({}.{}) wird nicht unterstützt", f[3], f[0], f[1]))?;
        let col = Column {
            name: f[1].to_string(),
            udt: f[3].to_string(),
            max_len,
            nullable: f[5] == "1",
            generated: f[6] == "1",
            pk: f[7] == "1",
            kind,
        };
        let ord: i64 = f[2].parse().map_err(|_| format!("columns.tsv Zeile {}: Ordinal", ln + 1))?;
        map.entry(f[0].to_string()).or_default().push((ord, col));
    }
    Ok(map
        .into_iter()
        .map(|(name, mut cols)| {
            cols.sort_by_key(|(o, _)| *o);
            Table { name, columns: cols.into_iter().map(|(_, c)| c).collect() }
        })
        .collect())
}

/// (app, name) of all migrations that a freshly migrated v3.4.2 DB has in `django_migrations`.
pub fn expected_migrations() -> BTreeSet<(String, String)> {
    pairs(MIGRATIONS, 2).into_iter().map(|v| (v[0].clone(), v[1].clone())).collect()
}

/// (app, name) → (app, squashed_name): migrations that were replaced by a squashed migration.
/// Older, incrementally upgraded installations additionally have these rows.
pub fn replaced_migrations() -> BTreeMap<(String, String), (String, String)> {
    pairs(REPLACED, 4).into_iter().map(|v| ((v[0].clone(), v[1].clone()), (v[2].clone(), v[3].clone()))).collect()
}

fn pairs(tsv: &str, n: usize) -> Vec<Vec<String>> {
    tsv.lines()
        .map(|l| l.trim_end_matches('\r'))
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .map(|l| l.split('\t').map(str::to_string).collect::<Vec<_>>())
        .filter(|v| v.len() == n)
        .collect()
}

/// Result of the migration state comparison.
/// All migration names of the paperless apps that ever existed up to v3.4.2 (git history).
pub fn historical_migrations() -> BTreeSet<(String, String)> {
    pairs(HISTORICAL, 2).into_iter().map(|v| (v[0].clone(), v[1].clone())).collect()
}

#[derive(Debug, Default)]
pub struct MigrationCheck {
    /// expected, but not applied in the source → source is older
    pub missing: Vec<(String, String)>,
    /// unknown rows of an installed app → source is newer or foreign
    pub unknown: Vec<(String, String)>,
    /// replaced by squashed migration (harmless)
    pub replaced_present: usize,
    /// Legacy: migrations that used to exist in paperless (file since deleted; harmless,
    /// Django ignores such rows)
    pub historical_present: usize,
    /// Rows of apps that v3.4.2 no longer installs (e.g. django_q from paperless-ng; harmless)
    pub foreign_apps: Vec<(String, String)>,
    /// known migrations of a newer paperless-ngx version ([`KNOWN_NEWER`]; accepted)
    pub newer: Vec<(String, String)>,
}

impl MigrationCheck {
    /// documents.0028 applied: documents_tag without the treenode columns.
    pub fn tag_tree_dropped(&self) -> bool {
        self.newer.iter().any(|(a, n)| a == "documents" && n == "0028_replace_tag_tree_fields")
    }
}

impl MigrationCheck {
    pub fn ok(&self) -> bool {
        self.missing.is_empty() && self.unknown.is_empty()
    }
}

/// Source must have all expected migrations. Additional rows are only allowed if they
/// (a) were replaced by an applied squashed migration, (b) come from the paperless history
/// up to v3.4.2 or (c) belong to an app that v3.4.2 does not install at all. Exactly these
/// rows are also ignored by Django on `migrate`. Everything else (e.g. `documents.0028_…` of a
/// newer version) → abort.
pub fn check_migrations(source: &BTreeSet<(String, String)>) -> MigrationCheck {
    let expected = expected_migrations();
    let replaced = replaced_migrations();
    let historical = historical_migrations();
    let apps: BTreeSet<&String> = expected.iter().map(|(a, _)| a).collect();
    let mut r = MigrationCheck::default();
    for m in &expected {
        if !source.contains(m) {
            r.missing.push(m.clone());
        }
    }
    for m in source {
        if expected.contains(m) {
            continue;
        }
        if matches!(replaced.get(m), Some(squash) if expected.contains(squash)) {
            r.replaced_present += 1;
        } else if KNOWN_NEWER.iter().any(|(a, n)| *a == m.0 && *n == m.1) {
            r.newer.push(m.clone());
        } else if historical.contains(m) {
            r.historical_present += 1;
        } else if !apps.contains(&m.0) {
            r.foreign_apps.push(m.clone());
        } else {
            r.unknown.push(m.clone());
        }
    }
    r
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_schema_parses() {
        let t = tables().unwrap();
        assert!(t.iter().any(|t| t.name == "documents_document"), "documents_document fehlt");
        assert!(t.iter().any(|t| t.name == "django_migrations"));
        for tab in &t {
            assert!(tab.pk().is_some(), "Tabelle ohne Primärschlüssel: {}", tab.name);
        }
        assert!(!expected_migrations().is_empty());
        assert!(PRE_DATA.contains("CREATE TABLE public.documents_document"));
        assert!(!PRE_DATA.contains("set_config"));
        assert!(POST_DATA.contains("FOREIGN KEY"));
        assert!(post_data().contains("WHERE (\"type\" IN ('totp', 'recovery_codes'));"), "mfa-Index nicht ersetzt");
    }

    #[test]
    fn migration_check_logic() {
        let exp = expected_migrations();
        let mut src = exp.clone();
        assert!(check_migrations(&src).ok());
        // Legacy from the history (file no longer exists in v3.4.2) and app that v3.4.2 does not know
        let hist = historical_migrations().into_iter().find(|m| !exp.contains(m)).unwrap();
        src.insert(hist);
        src.insert(("django_q".into(), "0001_initial".into()));
        let r = check_migrations(&src);
        assert!(r.ok(), "{r:?}");
        assert_eq!(r.historical_present, 1);
        assert_eq!(r.foreign_apps.len(), 1);
        src.insert(("documents".into(), "9999_future".into()));
        assert_eq!(check_migrations(&src).unknown.len(), 1);
        let first = exp.iter().next().unwrap().clone();
        src.remove(&first);
        assert_eq!(check_migrations(&src).missing, vec![first]);
    }

    #[test]
    fn known_newer_and_v220() {
        let mut src = expected_migrations();
        for (a, n) in KNOWN_NEWER {
            src.insert((a.to_string(), n.to_string()));
        }
        let r = check_migrations(&src);
        assert!(r.ok(), "{r:?}");
        assert_eq!(r.newer.len(), 2);
        assert!(r.tag_tree_dropped());
        src.insert(("documents".into(), "0030_future".into()));
        assert_eq!(check_migrations(&src).unknown.len(), 1);
        // embedded 2.20 schema
        let t = v220::tables().unwrap();
        let doc = t.iter().find(|t| t.name == "documents_document").unwrap();
        assert!(doc.columns.iter().any(|c| c.name == "storage_type"));
        assert!(!doc.columns.iter().any(|c| c.name == "root_document_id"));
        assert!(!t.iter().any(|t| v220::dropped_table(&t.name)));
        assert!(v220::expected_migrations().contains(&("documents".into(), "1075_workflowaction_order".into())));
        assert!(!v220::PRE_DATA.contains("set_config"));
        let tag = tables().unwrap().into_iter().find(|t| t.name == "documents_tag").unwrap();
        for c in TREENODE_DERIVED {
            assert!(tag.columns.iter().any(|x| x.name == *c), "{c}");
        }
    }
}
