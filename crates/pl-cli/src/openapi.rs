/// GET `/static/drf_spectacular_sidecar/swagger-ui-dist/{file}` (embedded sidecar files).
async fn swagger_asset(Path(file): Path<String>) -> Response {
    let Some((_, ct, gz)) = ASSETS.iter().find(|(n, _, _)| *n == file) else {
        return (StatusCode::NOT_FOUND, "Not Found").into_response();
    };
    let mut r = (StatusCode::OK, gunzip(gz)).into_response();
    if let Ok(v) = HeaderValue::from_str(ct) {
        r.headers_mut().insert(header::CONTENT_TYPE, v);
    }
    r.headers_mut().insert(header::CACHE_CONTROL, HeaderValue::from_static("max-age=60, public"));
    r
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn negotiation_like_drf() {
        assert_eq!(negotiate(None, None).unwrap().0, Kind::Yaml);
        assert_eq!(negotiate(Some("*/*"), None).unwrap().0, Kind::Yaml);
        assert_eq!(negotiate(Some("application/json"), None).unwrap().0, Kind::Json2);
        assert_eq!(negotiate(Some("application/yaml"), None).unwrap().0, Kind::Yaml2);
        assert_eq!(negotiate(Some("application/vnd.oai.openapi+json"), None).unwrap().0, Kind::Json);
        assert_eq!(negotiate(Some("*/*"), Some("json")).unwrap().0, Kind::Json);
        assert_eq!(negotiate(Some("*/*"), Some("xml")), Err(NegotiationError::NotFound));
        assert_eq!(negotiate(Some("text/html"), None), Err(NegotiationError::NotAcceptable));
        let (k, acc) = negotiate(Some("application/json; version=9"), None).unwrap();
        assert_eq!(k, Kind::Json2);
        assert_eq!(MediaType::parse(&acc).param("version"), Some("9"));
        let (k, acc) = negotiate(Some("*/*; version=9"), None).unwrap();
        assert_eq!(k, Kind::Yaml);
        assert_eq!(acc, "application/vnd.oai.openapi;version=9");
        let (_, acc) = negotiate(Some("application/*; version=9"), None).unwrap();
        assert_eq!(acc, "application/vnd.oai.openapi;version=9");
        let (_, acc) = negotiate(Some("application/json; version=9"), None).unwrap();
        assert_eq!(acc, "application/json; version=9");
    }

    #[test]
    fn swagger_negotiation_like_drf() {
        assert_eq!(negotiate_html(None, None).unwrap(), "text/html");
        assert_eq!(negotiate_html(Some("application/json; version=10"), None), Err(NegotiationError::NotAcceptable));
        assert_eq!(negotiate_html(Some("text/html; version=10"), None).unwrap(), "text/html; version=10");
        assert_eq!(negotiate_html(Some("*/*; version=9"), None).unwrap(), "text/html;version=9");
        assert_eq!(negotiate_html(Some("application/json, text/*"), None).unwrap(), "text/html");
        assert_eq!(negotiate_html(Some("*/*"), Some("json")), Err(NegotiationError::NotFound));
        assert_eq!(negotiate_html(Some("*/*"), Some("html")).unwrap(), "text/html");
        assert_eq!(negotiate_html(Some("*/*"), Some("")).unwrap(), "text/html");
        assert_eq!(negotiate(Some("*/*"), Some("")).unwrap().0, Kind::Yaml);
        assert_eq!(html_exception(StatusCode::NOT_ACCEPTABLE).status(), StatusCode::NOT_ACCEPTABLE);
    }

    #[test]
    fn embedded_bodies() {
        let j = body(Kind::Json, "10");
        let v: serde_json::Value = serde_json::from_slice(j).unwrap();
        assert_eq!(v["info"]["version"], "6.0.0 (10)");
        assert_eq!(v["info"]["title"], "PaperRust REST API");
        assert!(std::str::from_utf8(body(Kind::Yaml, "10")).unwrap().contains("title: PaperRust REST API\n"));
        assert!(std::str::from_utf8(body(Kind::Yaml, "9")).unwrap().contains("version: 6.0.0 (9)"));
        assert_eq!(error_body(Kind::Yaml, "Not found.", "not_found"), b"detail:\n  string: Not found.\n  code: not_found\n");
        assert_eq!(error_body(Kind::Json, "x \"y\"", "c"), b"{\n    \"detail\": \"x \\\"y\\\"\"\n}");
        assert_eq!(escapejs("/api/schema/?lang=de"), "/api/schema/?lang\\u003Dde");
        assert_eq!(routes().len(), 3);
    }
}
