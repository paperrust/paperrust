//! OpenAPI schema `/api/schema/` and Swagger UI `/api/schema/view/` (+ Swagger files).
//!
//! upstream: src/paperless/urls.py (`SpectacularAPIView`, `SpectacularSwaggerView`),
//! src/paperless/settings/__init__.py (`SPECTACULAR_SETTINGS`, `REST_FRAMEWORK`:
//! AcceptHeaderVersioning, DEFAULT_VERSION 10, ALLOWED_VERSIONS 9/10), drf-spectacular 0.29
//! (`views.py`, `renderers.py`: YAML `application/vnd.oai.openapi` + `application/yaml`, JSON
//! `application/vnd.oai.openapi+json` + `application/json`), DRF `negotiation.py`
//! (`DefaultContentNegotiation`: `?format=`, Accept without q values, precedence), `versioning.py`,
//! drf-spectacular-sidecar 2026.10.1 (Swagger UI, Apache-2.0).
//!
//! The schema responses are embedded byte-identically (generated by Django v3.4.2 with the reference
//! configuration, in English), see `tests/parity/pl-cli/gen_schema_assets.sh`.

