fn gunzip(b: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    let _ = flate2::read::GzDecoder::new(b).read_to_end(&mut out);
    out
}

/// Replace the product name in the embedded upstream schema (title, description, server texts);
/// the gz files remain unchanged upstream data.
fn rebrand(raw: Vec<u8>) -> Vec<u8> {
    match String::from_utf8(raw) {
        Ok(text) => text
            .replacen("Paperless-ngx REST API", TITLE, 1)
            .replacen("OpenAPI Spec for Paperless-ngx", "OpenAPI Spec for PaperRust", 1)
            .replace("of the Paperless-NGX server", "of the PaperRust server")
            .into_bytes(),
        Err(e) => e.into_bytes(),
    }
}

fn body(kind: Kind, version: &str) -> &'static [u8] {
    static CACHE: OnceLock<BTreeMap<(bool, bool), Vec<u8>>> = OnceLock::new();
    let m = CACHE.get_or_init(|| {
        let mut m = BTreeMap::new();
        m.insert((true, true), rebrand(gunzip(JSON10)));
        m.insert((true, false), rebrand(gunzip(JSON9)));
        m.insert((false, true), rebrand(gunzip(YAML10)));
        m.insert((false, false), rebrand(gunzip(YAML9)));
        m
    });
    m.get(&(kind.is_json(), version == "10")).map(Vec::as_slice).unwrap_or(&[])
}

/// Renderers of `SpectacularAPIView` in order.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Yaml,
    Yaml2,
    Json,
    Json2,
}

const RENDERERS: [Kind; 4] = [Kind::Yaml, Kind::Yaml2, Kind::Json, Kind::Json2];

impl Kind {
    fn media_type(self) -> &'static str {
        match self {
            Kind::Yaml => "application/vnd.oai.openapi",
            Kind::Yaml2 => "application/yaml",
            Kind::Json => "application/vnd.oai.openapi+json",
            Kind::Json2 => "application/json",
        }
    }
    fn format(self) -> &'static str {
        if self.is_json() { "json" } else { "yaml" }
    }
    fn is_json(self) -> bool {
        matches!(self, Kind::Json | Kind::Json2)
    }
    fn content_type(self) -> &'static str {
        match self {
            Kind::Yaml => "application/vnd.oai.openapi; charset=utf-8",
            Kind::Yaml2 => "application/yaml; charset=utf-8",
            Kind::Json => "application/vnd.oai.openapi+json",
            Kind::Json2 => "application/json",
        }
    }
}

/// DRF `_MediaType`.
#[derive(Debug, Clone)]
struct MediaType {
    raw: String,
    main: String,
    sub: String,
    params: Vec<(String, String)>,
}

impl MediaType {
    fn parse(s: &str) -> MediaType {
        let mut parts = s.split(';');
        let full = parts.next().unwrap_or("").trim();
        let (main, sub) = match full.split_once('/') {
            Some((m, s)) => (m.trim().to_string(), s.trim().to_string()),
            None => (full.to_string(), String::new()),
        };
        let mut params = Vec::new();
        for p in parts {
            if let Some((k, v)) = p.split_once('=') {
                let v = v.trim();
                let v = v.strip_prefix('"').and_then(|x| x.strip_suffix('"')).unwrap_or(v);
                params.push((k.trim().to_lowercase(), v.to_string()));
            }
        }
        MediaType { raw: s.to_string(), main, sub, params }
    }

    fn precedence(&self) -> u8 {
        if self.main == "*" {
            0
        } else if self.sub == "*" {
            1
        } else if self.params.is_empty() || (self.params.len() == 1 && self.params[0].0 == "q") {
            2
        } else {
            3
        }
    }

    /// `renderer.match(other)`
    fn renderer_matches(renderer: &MediaType, other: &MediaType) -> bool {
        if renderer.sub != "*" && other.sub != "*" && other.sub != renderer.sub {
            return false;
        }
        if renderer.main != "*" && other.main != "*" && other.main != renderer.main {
            return false;
        }
        true
    }

    fn param(&self, k: &str) -> Option<&str> {
        self.params.iter().find(|(x, _)| x == k).map(|(_, v)| v.as_str())
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum NegotiationError {
    /// `?format=` without a matching renderer → Http404
    NotFound,
    /// no renderer matches → 406
    NotAcceptable,
}

/// `DefaultContentNegotiation.select_renderer` → (renderer, accepted media type text).
pub fn negotiate(accept: Option<&str>, format: Option<&str>) -> Result<(Kind, String), NegotiationError> {
    // `if format:` – an empty `?format=` is ignored
    let format = format.filter(|f| !f.is_empty());
    let renderers: Vec<Kind> = match format {
        Some(f) => {
            let r: Vec<Kind> = RENDERERS.iter().copied().filter(|k| k.format() == f).collect();
            if r.is_empty() {
                return Err(NegotiationError::NotFound);
            }
            r
        }
        None => RENDERERS.to_vec(),
    };
    let header = accept.unwrap_or("*/*");
    let accepts: Vec<MediaType> = header.split(',').map(|t| MediaType::parse(t.trim())).collect();
    for prec in [3u8, 2, 1, 0] {
        let set: Vec<&MediaType> = accepts.iter().filter(|m| m.precedence() == prec).collect();
        if set.is_empty() {
            continue;
        }
        for r in &renderers {
            let rm = MediaType::parse(r.media_type());
            for m in &set {
                if MediaType::renderer_matches(&rm, m) {
                    // DRF: renderer more specific than the client's type (e.g. `*/*`) →
                    // renderer type + client params; otherwise the client's type verbatim.
                    let full = if rm.precedence() > m.precedence() {
                        let mut s = r.media_type().to_string();
                        for (k, v) in &m.params {
                            s.push_str(&format!(";{k}={v}"));
                        }
                        s
                    } else {
                        m.raw.trim().to_string()
                    };
                    return Ok((*r, full));
                }
            }
        }
    }
    Err(NegotiationError::NotAcceptable)
}

/// `DefaultContentNegotiation.select_renderer` for `SpectacularSwaggerView`
/// (`renderer_classes = [TemplateHTMLRenderer]`: media type `text/html`, format `html`)
/// → accepted media type text.
pub fn negotiate_html(accept: Option<&str>, format: Option<&str>) -> Result<String, NegotiationError> {
    const HTML: &str = "text/html";
    if format.filter(|f| !f.is_empty()).is_some_and(|f| f != "html") {
        return Err(NegotiationError::NotFound);
    }
    let rm = MediaType::parse(HTML);
    let header = accept.unwrap_or("*/*");
    let accepts: Vec<MediaType> = header.split(',').map(|t| MediaType::parse(t.trim())).collect();
    for prec in [3u8, 2, 1, 0] {
        for m in accepts.iter().filter(|m| m.precedence() == prec) {
            if MediaType::renderer_matches(&rm, m) {
                return Ok(if rm.precedence() > m.precedence() {
                    let mut s = HTML.to_string();
                    for (k, v) in &m.params {
                        s.push_str(&format!(";{k}={v}"));
                    }
                    s
                } else {
                    m.raw.trim().to_string()
                });
            }
        }
    }
    Err(NegotiationError::NotAcceptable)
}

/// `TemplateHTMLRenderer` for an exception without `<status>.html`/`api_exception.html`
/// template: body `"%d %s" % (status, status_text.title())`, `text/html; charset=utf-8`.
fn html_exception(status: StatusCode) -> Response {
    let reason = status.canonical_reason().unwrap_or("");
    let mut r = (status, format!("{} {reason}", status.as_u16())).into_response();
    r.headers_mut().insert(header::CONTENT_TYPE, HeaderValue::from_static("text/html; charset=utf-8"));
    r.headers_mut().insert(header::ALLOW, HeaderValue::from_static(ALLOW_READ_ONLY));
    r
}

fn error_body(kind: Kind, detail: &str, code: &str) -> Vec<u8> {
    if kind.is_json() {
        let mut m = serde_json::Map::new();
        m.insert("detail".into(), serde_json::Value::String(detail.into()));
        crate::pyjson::dumps(&serde_json::Value::Object(m), Some(4)).into_bytes()
    } else {
        // drf-spectacular YAML renderer represents ErrorDetail as {string, code}
        format!("detail:\n  string: {detail}\n  code: {code}\n").into_bytes()
    }
}

fn respond(status: StatusCode, kind: Kind, body: Vec<u8>) -> Response {
    let mut r = (status, body).into_response();
    r.headers_mut().insert(header::CONTENT_TYPE, HeaderValue::from_static(kind.content_type()));
    r
}

fn auth_code(e: &AuthError) -> &'static str {
    match e {
        AuthError::AuthenticationFailed { .. } => "authentication_failed",
        AuthError::PermissionDenied { .. } => "permission_denied",
        AuthError::NotFound { .. } => "not_found",
        _ => "not_authenticated",
    }
}

fn auth_error(e: AuthError, kind: Kind) -> Response {
    let status = e.status();
    let detail = e.detail();
    let code = auth_code(&e);
    let base = e.into_response();
    let www = base.headers().get(header::WWW_AUTHENTICATE).cloned();
    let mut r = respond(status, kind, error_body(kind, &detail, code));
    if let Some(w) = www {
        r.headers_mut().insert(header::WWW_AUTHENTICATE, w);
    }
    r
}

/// GET `/api/schema/`.
async fn schema(headers: HeaderMap, Query(q): Query<Vec<(String, String)>>, auth: Result<MaybeUser, AuthError>) -> Response {
    let format = q.iter().rev().find(|(k, _)| k == "format").map(|(_, v)| v.as_str());
    let accept = headers.get(header::ACCEPT).and_then(|v| v.to_str().ok());
    let (kind, accepted) = match negotiate(accept, format) {
        Ok(x) => x,
        Err(NegotiationError::NotFound) => {
            return respond(StatusCode::NOT_FOUND, Kind::Yaml, error_body(Kind::Yaml, "Not found.", "not_found"));
        }
        Err(NegotiationError::NotAcceptable) => {
            return respond(
                StatusCode::NOT_ACCEPTABLE,
                Kind::Yaml,
                error_body(Kind::Yaml, "Could not satisfy the request Accept header.", "not_acceptable"),
            );
        }
    };
    let mt = MediaType::parse(&accepted);
    let version = mt.param("version").unwrap_or(DEFAULT_VERSION).to_string();
    if !(version == DEFAULT_VERSION || ALLOWED_VERSIONS.contains(&version.as_str())) {
        return respond(StatusCode::NOT_ACCEPTABLE, kind, error_body(kind, "Invalid version in \"Accept\" header.", "not_acceptable"));
    }
    if let Err(e) = auth {
        return auth_error(e, kind);
    }
    let mut r = respond(StatusCode::OK, kind, body(kind, &version).to_vec());
    let disp = format!("inline; filename=\"{TITLE} ({version}).{}\"", kind.format());
    if let Ok(v) = HeaderValue::from_str(&disp) {
        r.headers_mut().insert(header::CONTENT_DISPOSITION, v);
    }
    r
}

/// Django `escapejs`.
pub fn escapejs(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' | '\'' | '"' | '>' | '<' | '&' | '=' | '-' | ';' | '`' | '\u{2028}' | '\u{2029}' => {
                out.push_str(&format!("\\u{:04X}", c as u32));
            }
            c if (c as u32) < 32 => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

/// `urllib.parse.quote_plus`.
fn quote_plus(s: &str) -> String {
    let mut out = String::new();
    for b in s.bytes() {
        match b {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'_' | b'.' | b'-' | b'~' => out.push(b as char),
            b' ' => out.push('+'),
            _ => out.push_str(&format!("%{b:02X}")),
        }
    }
    out
}

/// GET `/api/schema/view/`.
async fn swagger(
    State(st): State<AppState>,
    headers: HeaderMap,
    Query(q): Query<Vec<(String, String)>>,
    auth: Result<MaybeUser, AuthError>,
) -> Response {
    let allow = HeaderValue::from_static(ALLOW_READ_ONLY);
    // APIView.initial: content negotiation and versioning come before authentication.
    let format = q.iter().rev().find(|(k, _)| k == "format").map(|(_, v)| v.as_str());
    let accept = headers.get(header::ACCEPT).and_then(|v| v.to_str().ok());
    let accepted = match negotiate_html(accept, format) {
        Ok(a) => a,
        Err(NegotiationError::NotFound) => return html_exception(StatusCode::NOT_FOUND),
        Err(NegotiationError::NotAcceptable) => return html_exception(StatusCode::NOT_ACCEPTABLE),
    };
    // AcceptHeaderVersioning on the accepted media type ("Invalid version in "Accept" header.")
    let version = MediaType::parse(&accepted).param("version").unwrap_or(DEFAULT_VERSION).to_string();
    if !(version == DEFAULT_VERSION || ALLOWED_VERSIONS.contains(&version.as_str())) {
        return html_exception(StatusCode::NOT_ACCEPTABLE);
    }
    if let Err(e) = auth {
        let status = e.status();
        let www = e.into_response().headers().get(header::WWW_AUTHENTICATE).cloned();
        let mut r = html_exception(status);
        if let Some(w) = www {
            r.headers_mut().insert(header::WWW_AUTHENTICATE, w);
        }
        return r;
    }
    let cfg = st.config();
    // get_token(): secret from the cookie, otherwise new; the response sets the cookie (Django ≥ 4.1: unmasked)
    let cookies = pl_authz::csrf::parse_cookies(&headers);
    let secret = pl_authz::csrf::cookie(&cookies, &cfg.csrf_cookie_name)
        .filter(|c| pl_authz::csrf::check_token_format(c).is_ok())
        .map(|c| {
            if c.len() == pl_authz::csrf::CSRF_TOKEN_LENGTH {
                pl_authz::csrf::unmask_cipher_token(c).unwrap_or_default()
            } else {
                c.to_string()
            }
        })
        .filter(|s| s.len() == pl_authz::csrf::CSRF_SECRET_LENGTH)
        .unwrap_or_else(|| pl_authz::hashers::get_random_string(pl_authz::csrf::CSRF_SECRET_LENGTH));
    let token = pl_authz::csrf::mask_cipher_secret(&secret);
    let script = cfg.force_script_name.clone().unwrap_or_default();
    let mut schema_url = format!("{script}/api/schema/");
    let mut qp = Vec::new();
    for key in ["lang", "version"] {
        if let Some((_, v)) = q.iter().rev().find(|(k, _)| k == key) {
            qp.push(format!("{key}={}", quote_plus(v)));
        }
    }
    if !qp.is_empty() {
        schema_url.push('?');
        schema_url.push_str(&qp.join("&"));
    }
    let html = SWAGGER_HTML
        .replace("{{CSRF_TOKEN}}", &token)
        .replace("{{SCHEMA_URL}}", &escapejs(&schema_url))
        .replace("{{STATIC_URL}}", &cfg.static_url);
    let mut r = (StatusCode::OK, html).into_response();
    let h = r.headers_mut();
    h.insert(header::CONTENT_TYPE, HeaderValue::from_static("text/html; charset=utf-8"));
    h.insert("cross-origin-opener-policy", HeaderValue::from_static("unsafe-none"));
    h.insert(header::ALLOW, allow);
    let expires = (chrono::Utc::now() + chrono::Duration::seconds(31_449_600)).format("%a, %d %b %Y %H:%M:%S GMT");
    let cookie = format!("{}={secret}; expires={expires}; Max-Age=31449600; Path=/; SameSite=Lax", cfg.csrf_cookie_name);
    if let Ok(v) = HeaderValue::from_str(&cookie) {
        h.append(header::SET_COOKIE, v);
    }
    r
}

