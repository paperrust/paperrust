-- PaperRust: device token (docs/SYNC.md §8, ROADMAP-NEXT P3b). Crate: pl-authz (`device`).
-- Contract: docs/contract/pl-authz.md ("Device token").
--
-- * expand-only: only one new table with prefix paperrust_, no change to Django tables.
--   FK to auth_user with ON DELETE CASCADE: if Django deletes a user, their
--   device tokens disappear with them (Django does not know the table, the DB cascade handles it).
-- * idempotent (IF NOT EXISTS), may run several times.
-- * only sha256(token) (hex) is stored, never the plaintext.
-- * Rollback: DROP TABLE paperrust_device_token; (no upstream data affected)

CREATE TABLE IF NOT EXISTS paperrust_device_token (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid        uuid         NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    user_id     integer      NOT NULL REFERENCES auth_user (id) ON DELETE CASCADE,
    name        varchar(128) NOT NULL,
    token_hash  char(64)     NOT NULL UNIQUE,
    created     timestamptz  NOT NULL DEFAULT now(),
    last_used   timestamptz,
    revoked_at  timestamptz
);
CREATE INDEX IF NOT EXISTS paperrust_device_token_user_idx ON paperrust_device_token (user_id);
