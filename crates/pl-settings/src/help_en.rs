/// English text for `key` (key as in `SCHEMA`).
pub fn help_en(key: &str) -> Option<&'static str> {
    HELP_EN.iter().find(|(k, _)| *k == key).map(|(_, t)| *t)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::SCHEMA;
    use std::collections::HashSet;

    #[test]
    fn help_en_complete() {
        let schema: Vec<&str> = SCHEMA.iter().map(|d| d.key).collect();
        let table: Vec<&str> = HELP_EN.iter().map(|(k, _)| *k).collect();
        // same keys, same order, no duplicates
        assert_eq!(table, schema, "HELP_EN muss SCHEMA 1:1 folgen");
        assert_eq!(table.iter().collect::<HashSet<_>>().len(), table.len());
        for (k, t) in HELP_EN {
            assert!(!t.trim().is_empty(), "{k}: leerer Text");
            assert!(!t.chars().any(|c| "äöüÄÖÜß„“".contains(c)), "{k}: Text sieht deutsch aus: {t}");
        }
    }

    #[test]
    fn help_en_lookup() {
        assert_eq!(help_en("PAPERLESS_EMAIL_HOST"), Some("SMTP server"));
        assert_eq!(help_en("NOPE"), None);
        let d = crate::schema::find("PAPERLESS_TIME_ZONE").unwrap();
        assert_eq!(d.help_en(), "Time zone");
    }
}
