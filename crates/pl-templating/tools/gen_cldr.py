"""
Erzeugt src/cldr_data.rs aus den CLDR-Daten von Babel (gleiche Version wie upstream: babel==2.18.0).

Aufruf (Babel-Wheel entpackt in <dir>):  python -I gen_cldr.py <dir-mit-babel> <ausgabe.rs>
Format je Locale: Felder durch \x1f getrennt, Reihenfolge siehe FIELDS in src/localize.rs.
"""
import sys

sys.path.insert(0, sys.argv[1])
from babel import Locale, localedata  # noqa: E402

SEP = "\x1f"


def blob(loc: Locale) -> str:
    f = []
    for ctx in ("format", "stand-alone"):
        for width in ("abbreviated", "wide", "narrow"):
            m = loc.months[ctx][width]
            f += [m[i] for i in range(1, 13)]
    for ctx in ("format", "stand-alone"):
        for width in ("abbreviated", "wide", "short", "narrow"):
            d = loc.days[ctx][width]
            f += [d[i] for i in range(7)]  # 0 = Montag
    for width in ("abbreviated", "wide", "narrow"):
        f += [loc.eras[width][0], loc.eras[width][1]]
    for first in ("abbreviated", "wide", "narrow"):
        # like babel.dates.DateTimeFormat.format_period (character 'a')
        for period in ("am", "pm"):
            for width in (first, "wide", "narrow", "abbreviated"):
                names = loc.day_periods["format"][width]
                if period in names:
                    f.append(names[period])
                    break
            else:
                raise ValueError(period)
    for ctx in ("format", "stand-alone"):
        for width in ("abbreviated", "wide", "narrow"):
            q = loc.quarters[ctx][width]
            f += [q[i] for i in range(1, 5)]
    for kind in (loc.date_formats, loc.time_formats):
        for w in ("full", "long", "medium", "short"):
            f.append(kind[w].pattern)
    for w in ("full", "long", "medium", "short"):
        f.append(loc.datetime_formats[w])
    f.append(loc.zone_formats["gmt"])
    f.append(str(loc.first_week_day))
    f.append(str(loc.min_week_days))
    for x in f:
        assert SEP not in x and '"#' not in x, x
    return SEP.join(f)


def main() -> None:
    out = sys.argv[2]
    keys: dict[str, str] = {}
    for ident in localedata.locale_identifiers():
        loc = Locale.parse(ident)
        keys[ident] = str(loc)
        parts = ident.split("_")
        # Short form without script (e.g. sr_RS -> sr_Cyrl_RS) if Babel resolves it that way itself
        if len(parts) == 3 and len(parts[1]) == 4:
            short = f"{parts[0]}_{parts[2]}"
            try:
                if str(Locale.parse(short)) == str(loc) and short not in keys:
                    keys[short] = str(loc)
            except Exception:
                pass
    blobs: dict[str, int] = {}
    data: list[str] = []
    entries: list[tuple[str, int]] = []
    for key in sorted(keys):
        b = blob(Locale.parse(keys[key]))
        if b not in blobs:
            blobs[b] = len(data)
            data.append(b)
        entries.append((key, blobs[b]))
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// @generated by tools/gen_cldr.py from Babel 2.18.0 (CLDR) - do not edit by hand.\n")
        fh.write("// upstream: Babel locale data, used by src/documents/templating/filters.py (localize_date)\n\n")
        fh.write("pub(crate) static DATA: &[&str] = &[\n")
        for b in data:
            fh.write(f'    r#"{b}"#,\n')
        fh.write("];\n\n")
        fh.write("/// (Locale-Kennung, Index in DATA), sortiert nach Kennung.\n")
        fh.write("pub(crate) static LOCALES: &[(&str, u16)] = &[\n")
        for k, i in entries:
            fh.write(f'    ("{k}", {i}),\n')
        fh.write("];\n")
    print(len(entries), "locales", len(data), "blobs")


main()
