-- PaperRust: embedded task queue (replacement for the Redis/Celery broker and celery beat).
-- Crate: pl-queue. Contract: docs/contract/pl-queue.md.
--
-- * expand-only: only creates new tables/indexes with the prefix paperrust_, does not change any
--   upstream table (documents_paperlesstask is only written to, not altered).
-- * idempotent (IF NOT EXISTS), may run repeatedly.
-- * is NOT run automatically; the coordinator/operator applies it
--   (e.g. psql -f) or deliberately calls pl_queue::migrations::apply().
-- * Rollback: DROP TABLE paperrust_task_queue, paperrust_task_group, paperrust_beat_state;
--   (no upstream data affected).

CREATE TABLE IF NOT EXISTS paperrust_task_queue (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Celery task ID (UUID as text, like documents_paperlesstask.task_id varchar(72))
    task_id         varchar(72)  NOT NULL UNIQUE,
    -- full Celery name, e.g. documents.tasks.train_classifier
    task_name       varchar(255) NOT NULL,
    queue           varchar(100) NOT NULL DEFAULT 'celery',
    -- 0 = highest priority (like kombu/Redis), 0..9
    priority        smallint     NOT NULL DEFAULT 0,
    args            jsonb        NOT NULL DEFAULT '[]'::jsonb,
    kwargs          jsonb        NOT NULL DEFAULT '{}'::jsonb,
    headers         jsonb        NOT NULL DEFAULT '{}'::jsonb,
    -- queued | running | done | failed | revoked
    state           varchar(16)  NOT NULL DEFAULT 'queued',
    -- Deliveries since the last enqueue/retry (crash detection, fencing token)
    attempts        integer      NOT NULL DEFAULT 0,
    -- Celery request.retries (number of task.retry() calls)
    retries         integer      NOT NULL DEFAULT 0,
    -- earliest start (Celery eta/countdown)
    eta             timestamptz  NOT NULL DEFAULT now(),
    -- Celery expires (absolute); afterwards REVOKED instead of execution
    expires         timestamptz,
    -- hard time limit in seconds (NULL = worker default PAPERLESS_WORKER_TIMEOUT)
    time_limit      double precision,
    locked_by       varchar(255),
    locked_until    timestamptz,
    heartbeat_at    timestamptz,
    revoke_requested boolean     NOT NULL DEFAULT false,
    terminate_requested boolean  NOT NULL DEFAULT false,
    -- Canvas: callbacks/errbacks (list of signatures), group/chord
    link            jsonb        NOT NULL DEFAULT '[]'::jsonb,
    link_error      jsonb        NOT NULL DEFAULT '[]'::jsonb,
    group_id        varchar(72),
    group_index     integer,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    started_at      timestamptz,
    finished_at     timestamptz,
    result          jsonb,
    error           jsonb
);

CREATE INDEX IF NOT EXISTS paperrust_task_queue_claim_idx
    ON paperrust_task_queue (queue, priority, eta, id) WHERE state = 'queued';
CREATE INDEX IF NOT EXISTS paperrust_task_queue_lease_idx
    ON paperrust_task_queue (locked_until) WHERE state = 'running';
CREATE INDEX IF NOT EXISTS paperrust_task_queue_finished_idx
    ON paperrust_task_queue (finished_at) WHERE state IN ('done', 'failed', 'revoked');
CREATE INDEX IF NOT EXISTS paperrust_task_queue_group_idx
    ON paperrust_task_queue (group_id, group_index) WHERE group_id IS NOT NULL;

-- Groups/chords (celery group/chord): counters under row lock.
CREATE TABLE IF NOT EXISTS paperrust_task_group (
    group_id        varchar(72)  PRIMARY KEY,
    total           integer      NOT NULL,
    completed       integer      NOT NULL DEFAULT 0,
    failed          integer      NOT NULL DEFAULT 0,
    -- Chord body (signature) or NULL for a plain group
    body            jsonb,
    -- chord(...).on_error(sig): errback (signature) or NULL
    on_error        jsonb,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    finished_at     timestamptz
);

-- celery beat: last run per schedule entry (replaces celerybeat-schedule.db).
CREATE TABLE IF NOT EXISTS paperrust_beat_state (
    name            varchar(200) PRIMARY KEY,
    task            varchar(255) NOT NULL,
    last_run_at     timestamptz  NOT NULL,
    total_run_count integer      NOT NULL DEFAULT 0,
    tz              varchar(64)  NOT NULL
);
