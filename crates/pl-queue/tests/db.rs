//! DB tests for PgQueue/Worker/Beat against a **dedicated** test database (never `paperless`).
//!
//! Run:
//! ```text
//! createdb pl_queue_test   (as user paperless on 127.0.0.1:54329)
//! PAPERRUST_QUEUE_TEST_DATABASE_URL=postgres://paperless:paperless@127.0.0.1:54329/pl_queue_test \
//!   cargo test -p pl-queue -j 1 -- --ignored
//! ```
//! The tests create `documents_paperlesstask` (columns like upstream v3.4.2, without FK to
//! `auth_user`) and the pl-queue migration. Each test uses its own queue.

