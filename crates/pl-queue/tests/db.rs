const PAPERLESSTASK_DDL: &str = "CREATE TABLE IF NOT EXISTS documents_paperlesstask (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id integer,
    task_id varchar(72) NOT NULL UNIQUE,
    task_type varchar(50) NOT NULL,
    trigger_source varchar(50) NOT NULL,
    status varchar(30) NOT NULL,
    date_created timestamptz NOT NULL,
    date_started timestamptz,
    date_done timestamptz,
    duration_seconds double precision,
    wait_time_seconds double precision,
    input_data jsonb NOT NULL,
    result_data jsonb,
    acknowledged boolean NOT NULL)";

async fn pool() -> PgPool {
    let url = std::env::var("PAPERRUST_QUEUE_TEST_DATABASE_URL").expect("PAPERRUST_QUEUE_TEST_DATABASE_URL");
    assert!(
        url.trim_end_matches('/').rsplit('/').next().is_some_and(|db| db.starts_with("pl_queue_test")),
        "refusing to run against a non-test database"
    );
    let pool = sqlx::postgres::PgPoolOptions::new().max_connections(10).connect(&url).await.expect("connect");
    // Tests running in parallel: serialise DDL
    let mut tx = pool.begin().await.unwrap();
    sqlx::query("SELECT pg_advisory_xact_lock(4242)").execute(&mut *tx).await.unwrap();
    sqlx::raw_sql(PAPERLESSTASK_DDL).execute(&mut *tx).await.unwrap();
    for (_, sql) in pl_queue::migrations::ALL {
        sqlx::raw_sql(sql).execute(&mut *tx).await.unwrap();
    }
    tx.commit().await.unwrap();
    pool
}

fn cfg(queue: &str, extra: &[(&str, &str)]) -> QueueConfig {
    let mut pairs: Vec<(String, String)> = vec![
        ("PAPERRUST_QUEUE_BACKEND".into(), "postgres".into()),
        ("PAPERRUST_QUEUE_NAMES".into(), queue.into()),
        ("PAPERRUST_QUEUE_VISIBILITY_TIMEOUT".into(), "6".into()),
        ("PAPERRUST_QUEUE_POLL_INTERVAL".into(), "0.05".into()),
        ("PAPERRUST_QUEUE_SHUTDOWN_GRACE".into(), "5".into()),
        ("PAPERLESS_TASK_WORKERS".into(), "2".into()),
    ];
    for (k, v) in extra {
        pairs.retain(|(a, _)| a != k);
        pairs.push((k.to_string(), v.to_string()));
    }
    QueueConfig::from_env(&Env::from_pairs(pairs)).unwrap()
}

type Calls = Arc<Mutex<Vec<(String, Vec<Value>)>>>;

fn qname() -> String {
    format!("t-{}", Uuid::new_v4().simple())
}

fn opts(queue: &str) -> EnqueueOptions {
    EnqueueOptions { queue: Some(queue.to_string()), ..Default::default() }
}

fn kw(v: Value) -> Map<String, Value> {
    v.as_object().cloned().unwrap_or_default()
}

/// Start the worker; returns (stop sender, JoinHandle).
fn start(pool: &PgPool, handlers: Handlers, cfg: QueueConfig) -> (watch::Sender<bool>, tokio::task::JoinHandle<()>) {
    let (tx, rx) = watch::channel(false);
    let w = Worker::new(PgQueue::new(pool.clone(), cfg.max_deliveries), handlers, cfg, Default::default());
    (tx, tokio::spawn(w.run(rx)))
}

async fn wait_for<F, Fut>(what: &str, secs: u64, mut f: F)
where
    F: FnMut() -> Fut,
    Fut: std::future::Future<Output = bool>,
{
    let end = tokio::time::Instant::now() + Duration::from_secs(secs);
    while tokio::time::Instant::now() < end {
        if f().await {
            return;
        }
        tokio::time::sleep(Duration::from_millis(50)).await;
    }
    panic!("timeout waiting for {what}");
}

async fn queue_state(pool: &PgPool, id: Uuid) -> String {
    sqlx::query("SELECT state FROM paperrust_task_queue WHERE task_id = $1")
        .bind(id.to_string())
        .fetch_one(pool)
        .await
        .unwrap()
        .get("state")
}

async fn ptask(pool: &PgPool, id: Uuid) -> sqlx::postgres::PgRow {
    sqlx::query("SELECT * FROM documents_paperlesstask WHERE task_id = $1").bind(id.to_string()).fetch_one(pool).await.unwrap()
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn lifecycle_success_and_paperlesstask() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let o = EnqueueOptions { trigger_source: Some("manual".into()), ..opts(&q) };
    let id = queue.enqueue("documents.tasks.sanity_check", kw(json!({"raise_on_error": false})), o.clone()).await.unwrap();
    // idempotent: the same ID once more
    let again = queue.enqueue("documents.tasks.sanity_check", Map::new(), EnqueueOptions { task_id: Some(id), ..o }).await.unwrap();
    assert_eq!(again, id);
    let n: i64 = sqlx::query("SELECT count(*) AS n FROM paperrust_task_queue WHERE task_id = $1")
        .bind(id.to_string())
        .fetch_one(&pool)
        .await
        .unwrap()
        .get("n");
    assert_eq!(n, 1);
    let r = ptask(&pool, id).await;
    assert_eq!(r.get::<String, _>("status"), "pending");
    assert_eq!(r.get::<String, _>("task_type"), "sanity_check");
    assert_eq!(r.get::<String, _>("trigger_source"), "manual");
    assert_eq!(r.get::<Value, _>("input_data"), json!({}));
    assert!(!r.get::<bool, _>("acknowledged"));
    assert_eq!(queue.status(id).await.unwrap().unwrap().status, TaskStatus::Pending);

    // consume_file (JSON arguments) → input_data/owner like upstream; duplicate → failure
    let cid = queue
        .enqueue(
            "documents.tasks.consume_file",
            kw(json!({"input_doc": {"original_file": "/scratch/x/Rechnung.pdf", "mime_type": "application/pdf"}, "overrides": {"owner_id": null, "title": "R"}})),
            EnqueueOptions { trigger_source: Some("api_upload".into()), ..opts(&q) },
        )
        .await
        .unwrap();
    let r = ptask(&pool, cid).await;
    assert_eq!(
        r.get::<Value, _>("input_data"),
        json!({"filename": "Rechnung.pdf", "mime_type": "application/pdf", "overrides": {"title": "R"}})
    );
    assert_eq!(r.get::<Option<i32>, _>("owner_id"), None);

    let seen = Arc::new(Mutex::new(Vec::<(String, Map<String, Value>)>::new()));
    let s2 = seen.clone();
    let handlers = Handlers::new()
        .register("documents.tasks.sanity_check", move |ctx: TaskContext| {
            let s = s2.clone();
            async move {
                s.lock().unwrap().push((ctx.task_id.clone(), ctx.kwargs.clone()));
                tokio::time::sleep(Duration::from_millis(100)).await;
                Ok(Value::String("No issues detected.".into()))
            }
        })
        .register("documents.tasks.consume_file", |_ctx: TaskContext| async {
            Ok(json!({"duplicate_of": 7, "duplicate_in_trash": false}))
        });
    let (stop, h) = start(&pool, handlers, cfg(&q, &[]));
    let p = pool.clone();
    wait_for("both done", 20, || {
        let p = p.clone();
        async move {
            let n: i64 = sqlx::query("SELECT count(*) AS n FROM documents_paperlesstask WHERE task_id = ANY($1) AND date_done IS NOT NULL")
                .bind(vec![id.to_string(), cid.to_string()])
                .fetch_one(&p)
                .await
                .unwrap()
                .get("n");
            n == 2
        }
    })
    .await;
    stop.send(true).unwrap();
    h.await.unwrap();

    assert_eq!(seen.lock().unwrap().len(), 1);
    assert_eq!(seen.lock().unwrap()[0].1["raise_on_error"], json!(false));
    let r = ptask(&pool, id).await;
    assert_eq!(r.get::<String, _>("status"), "success");
    // string result → result_data stays NULL (only a dict is stored)
    assert_eq!(r.get::<Option<Value>, _>("result_data"), None);
    let started: chrono::DateTime<chrono::Utc> = r.get("date_started");
    let created: chrono::DateTime<chrono::Utc> = r.get("date_created");
    let done: chrono::DateTime<chrono::Utc> = r.get("date_done");
    assert!(created <= started && started <= done);
    let dur: f64 = r.get("duration_seconds");
    assert!(dur >= 0.09, "{dur}");
    assert!(r.get::<f64, _>("wait_time_seconds") >= 0.0);
    let info = queue.status(id).await.unwrap().unwrap();
    assert_eq!(info.status, TaskStatus::Success);
    assert_eq!(info.result, Some(json!("No issues detected.")));
    let r = ptask(&pool, cid).await;
    assert_eq!(r.get::<String, _>("status"), "failure");
    assert_eq!(r.get::<Value, _>("result_data"), json!({"duplicate_of": 7, "duplicate_in_trash": false}));
}

#[tokio::test(flavor = "multi_thread", worker_threads = 8)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn concurrent_workers_execute_each_task_once() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    const N: usize = 300;
    let mut ids = Vec::new();
    for i in 0..N {
        let o = EnqueueOptions { priority: Some((i % 3) as i16), ..opts(&q) };
        ids.push(queue.enqueue("test.count", kw(json!({"i": i})), o).await.unwrap());
    }
    let counts: Arc<Mutex<HashMap<String, (u32, String)>>> = Arc::default();
    let mut workers = Vec::new();
    for w in 0..4 {
        let c = counts.clone();
        let name = format!("w{w}");
        let n2 = name.clone();
        let handlers = Handlers::new().register("test.count", move |ctx: TaskContext| {
            let c = c.clone();
            let n = n2.clone();
            async move {
                tokio::time::sleep(Duration::from_millis(2)).await;
                let mut m = c.lock().unwrap();
                let e = m.entry(ctx.task_id.clone()).or_insert((0, n.clone()));
                e.0 += 1;
                Ok(Value::Null)
            }
        });
        workers.push(start(&pool, handlers, cfg(&q, &[("PAPERLESS_TASK_WORKERS", "3"), ("PAPERRUST_WORKER_NAME", &name)])));
    }
    let p = pool.clone();
    let qq = q.clone();
    wait_for("all done", 60, || {
        let p = p.clone();
        let qq = qq.clone();
        async move {
            let n: i64 = sqlx::query("SELECT count(*) AS n FROM paperrust_task_queue WHERE queue = $1 AND state = 'done'")
                .bind(qq)
                .fetch_one(&p)
                .await
                .unwrap()
                .get("n");
            n as usize == N
        }
    })
    .await;
    for (stop, h) in workers {
        stop.send(true).unwrap();
        h.await.unwrap();
    }
    let m = counts.lock().unwrap();
    assert_eq!(m.len(), N);
    assert!(m.values().all(|(n, _)| *n == 1), "a task ran twice");
    let per_worker: HashMap<&str, usize> = m.values().fold(HashMap::new(), |mut acc, (_, w)| {
        *acc.entry(w.as_str()).or_default() += 1;
        acc
    });
    assert!(per_worker.len() >= 2, "work was not shared: {per_worker:?}");
}

/// `PAPERLESS_TASK_WORKERS=3` in ONE worker: exactly 3 tasks run at the same time (never more),
/// each exactly once; on shutdown the running ones finish (grace) – no abort.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn one_worker_runs_task_workers_slots_concurrently() {
    use std::sync::atomic::{AtomicUsize, Ordering};
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    const N: usize = 9;
    let mut ids = Vec::new();
    for i in 0..N {
        ids.push(queue.enqueue("test.slot", kw(json!({"i": i})), opts(&q)).await.unwrap());
    }
    let now = Arc::new(AtomicUsize::new(0));
    let max = Arc::new(AtomicUsize::new(0));
    let runs: Calls = Arc::default();
    let (n2, m2, r2) = (now.clone(), max.clone(), runs.clone());
    let handlers = Handlers::new().register("test.slot", move |ctx: TaskContext| {
        let (now, max, runs) = (n2.clone(), m2.clone(), r2.clone());
        async move {
            let cur = now.fetch_add(1, Ordering::SeqCst) + 1;
            max.fetch_max(cur, Ordering::SeqCst);
            tokio::time::sleep(Duration::from_millis(400)).await;
            runs.lock().unwrap().push((ctx.task_id.clone(), ctx.args.clone()));
            now.fetch_sub(1, Ordering::SeqCst);
            Ok(Value::Null)
        }
    });
    let t = std::time::Instant::now();
    let (stop, h) = start(&pool, handlers, cfg(&q, &[("PAPERLESS_TASK_WORKERS", "3")]));
    let p = pool.clone();
    let qq = q.clone();
    // let the first 6 finish, then shut down during the third wave
    wait_for("6 done", 30, || {
        let (p, qq) = (p.clone(), qq.clone());
        async move {
            let n: i64 = sqlx::query("SELECT count(*) AS n FROM paperrust_task_queue WHERE queue = $1 AND state = 'done'")
                .bind(qq)
                .fetch_one(&p)
                .await
                .unwrap()
                .get("n");
            n >= 6
        }
    })
    .await;
    let p = pool.clone();
    let qq = q.clone();
    wait_for("third wave running", 10, || {
        let (p, qq) = (p.clone(), qq.clone());
        async move {
            let n: i64 = sqlx::query("SELECT count(*) AS n FROM paperrust_task_queue WHERE queue = $1 AND state = 'running'")
                .bind(qq)
                .fetch_one(&p)
                .await
                .unwrap()
                .get("n");
            n == 3
        }
    })
    .await;
    stop.send(true).unwrap();
    tokio::time::timeout(Duration::from_secs(10), h).await.expect("shutdown hangs").unwrap();
    let el = t.elapsed();
    assert_eq!(max.load(Ordering::SeqCst), 3, "exactly task_workers slots in parallel");
    let mut seen: Vec<String> = runs.lock().unwrap().iter().map(|(id, _)| id.clone()).collect();
    assert_eq!(seen.len(), N, "in-flight tasks finished during the shutdown grace");
    seen.sort();
    seen.dedup();
    assert_eq!(seen.len(), N, "no task ran twice");
    for id in ids {
        assert_eq!(queue_state(&pool, id).await, "done");
    }
    // 3 waves of 400 ms instead of 9 × 400 ms serially
    assert!(el < Duration::from_millis(3000), "not concurrent: {el:?}");
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn crashed_worker_task_is_redelivered_and_fenced() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let id = queue.enqueue("documents.tasks.train_classifier", Map::new(), opts(&q)).await.unwrap();
    // Worker A claims and "crashes" (no heartbeat, no completion)
    let a = queue.claim("crashy", std::slice::from_ref(&q), None, 10, 0.3).await.unwrap();
    assert_eq!(a.len(), 1);
    assert_eq!(queue.mark_started(&a[0], 0.3).await.unwrap(), Heartbeat::Ok);
    assert_eq!(queue.claim("other", std::slice::from_ref(&q), None, 10, 0.3).await.unwrap().len(), 0, "running job must not be claimable");
    tokio::time::sleep(Duration::from_millis(400)).await;
    // Cleanup (a parallel test worker may beat us to it – the result is the same)
    queue.reap_expired_leases().await.unwrap();
    assert_eq!(queue_state(&pool, id).await, "queued");
    // Worker B takes over and completes
    let b = queue.claim("healthy", std::slice::from_ref(&q), None, 10, 5.0).await.unwrap();
    assert_eq!(b.len(), 1);
    assert_eq!(b[0].attempts, 2);
    // A comes back: heartbeat/completion are rejected (fencing)
    assert_eq!(queue.heartbeat(&a[0], 5.0).await.unwrap(), Heartbeat::Lost);
    assert!(!queue.complete(&a[0], json!({"from": "A"})).await.unwrap());
    assert!(queue.complete(&b[0], Value::String("Training completed successfully".into())).await.unwrap());
    assert_eq!(queue_state(&pool, id).await, "done");
    assert_eq!(ptask(&pool, id).await.get::<String, _>("status"), "success");

    // Lost too often → FAILURE with WorkerLostError
    let id2 = queue.enqueue("documents.tasks.train_classifier", Map::new(), opts(&q)).await.unwrap();
    // max_deliveries = 3 (the same in all processes, see contract)
    for _ in 0..3 {
        let j = queue.claim("crashy", std::slice::from_ref(&q), None, 10, 0.2).await.unwrap();
        assert_eq!(j.len(), 1);
        tokio::time::sleep(Duration::from_millis(300)).await;
        queue.reap_expired_leases().await.unwrap();
    }
    assert_eq!(queue_state(&pool, id2).await, "failed");
    let r = ptask(&pool, id2).await;
    assert_eq!(r.get::<String, _>("status"), "failure");
    assert_eq!(r.get::<Value, _>("result_data")["error_type"], "WorkerLostError");

    // Worker loop: crash in the middle of execution (task aborted) → second worker
    let id3 = queue.enqueue("test.slow", Map::new(), opts(&q)).await.unwrap();
    let runs = Arc::new(Mutex::new(0u32));
    let r1 = runs.clone();
    let slow = Handlers::new().register("test.slow", move |_c: TaskContext| {
        let r = r1.clone();
        async move {
            *r.lock().unwrap() += 1;
            tokio::time::sleep(Duration::from_secs(30)).await;
            Ok(Value::Null)
        }
    });
    let (stop1, h1) = start(&pool, slow, cfg(&q, &[("PAPERRUST_WORKER_NAME", "dies")]));
    let p = pool.clone();
    wait_for("running", 10, || {
        let p = p.clone();
        async move { queue_state(&p, id3).await == "running" }
    })
    .await;
    h1.abort(); // hard crash: no release, no heartbeat any more
    let _ = h1.await;
    drop(stop1);
    let r2 = runs.clone();
    let fast = Handlers::new().register("test.slow", move |_c: TaskContext| {
        let r = r2.clone();
        async move {
            *r.lock().unwrap() += 1;
            Ok(json!({"ok": true}))
        }
    });
    let (stop2, h2) = start(&pool, fast, cfg(&q, &[("PAPERRUST_WORKER_NAME", "survivor")]));
    wait_for("redelivered", 20, || {
        let p = p.clone();
        async move { queue_state(&p, id3).await == "done" }
    })
    .await;
    stop2.send(true).unwrap();
    h2.await.unwrap();
    assert_eq!(*runs.lock().unwrap(), 2);
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn retries_time_limit_revoke_expire() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let fast = RetryPolicy { max_retries: Some(5), backoff_factor: 1, backoff_max: 1, jitter: true };
    let calls = Arc::new(Mutex::new(Vec::<i32>::new()));
    let c1 = calls.clone();
    let handlers = Handlers::new()
        .register_with_policy(
            "documents.tasks.apply_ai_suggestions",
            move |ctx: TaskContext| {
                let c = c1.clone();
                async move {
                    c.lock().unwrap().push(ctx.retries);
                    if ctx.retries < 2 { Err(TaskError::autoretry("LLMTimeoutError", "timeout")) } else { Ok(Value::Null) }
                }
            },
            Some(fast),
        )
        .register_with_policy(
            "test.always_fails",
            |_c: TaskContext| async { Err(TaskError::autoretry("SearchIndexLockError", "locked")) },
            Some(RetryPolicy { max_retries: Some(2), ..fast }),
        )
        .register("documents.tasks.empty_trash", |_c: TaskContext| async {
            tokio::time::sleep(Duration::from_secs(30)).await;
            Ok(Value::Null)
        })
        .register("documents.tasks.check_scheduled_workflows", |_c: TaskContext| async { Err(TaskError::fail("ValueError", "boom")) })
        .register("documents.tasks.llmindex_index", |_c: TaskContext| async {
            tokio::time::sleep(Duration::from_secs(30)).await;
            Ok(Value::Null)
        })
        .register("documents.tasks.build_share_link_bundle", |_c: TaskContext| async { Ok(Value::Null) })
        .register("documents.tasks.bulk_update_documents", |_c: TaskContext| async { Ok(Value::Null) });

    let ai = queue.enqueue("documents.tasks.apply_ai_suggestions", kw(json!({"action_id": 1, "document_id": 5})), opts(&q)).await.unwrap();
    assert_eq!(ptask(&pool, ai).await.get::<Value, _>("input_data"), json!({"document_id": 5}));
    let af = queue.enqueue("test.always_fails", Map::new(), opts(&q)).await.unwrap();
    let tl = queue.enqueue("documents.tasks.empty_trash", Map::new(), EnqueueOptions { time_limit: Some(0.3), ..opts(&q) }).await.unwrap();
    let fl = queue.enqueue("documents.tasks.check_scheduled_workflows", Map::new(), opts(&q)).await.unwrap();
    let ex = queue
        .enqueue(
            "documents.tasks.build_share_link_bundle",
            kw(json!({"bundle_id": 1})),
            EnqueueOptions { expires: Some(0.001), countdown: Some(0.2), ..opts(&q) },
        )
        .await
        .unwrap();
    let rv = queue
        .enqueue(
            "documents.tasks.bulk_update_documents",
            kw(json!({"document_ids": [1]})),
            EnqueueOptions { countdown: Some(60.0), ..opts(&q) },
        )
        .await
        .unwrap();
    assert!(queue.revoke(rv, false).await.unwrap());
    assert_eq!(ptask(&pool, rv).await.get::<String, _>("status"), "revoked");
    let term = queue.enqueue("documents.tasks.llmindex_index", Map::new(), opts(&q)).await.unwrap();

    let (stop, h) = start(&pool, handlers, cfg(&q, &[("PAPERLESS_TASK_WORKERS", "4")]));
    let p = pool.clone();
    wait_for("llm running", 10, || {
        let p = p.clone();
        async move { queue_state(&p, term).await == "running" }
    })
    .await;
    assert!(queue.revoke(term, true).await.unwrap());
    let all = vec![ai, af, tl, fl, ex, term];
    wait_for("all finished", 30, || {
        let p = p.clone();
        let all = all.clone();
        async move {
            let n: i64 = sqlx::query(
                "SELECT count(*) AS n FROM paperrust_task_queue WHERE task_id = ANY($1) AND state IN ('done','failed','revoked')",
            )
            .bind(all.iter().map(Uuid::to_string).collect::<Vec<_>>())
            .fetch_one(&p)
            .await
            .unwrap()
            .get("n");
            n == 6
        }
    })
    .await;
    stop.send(true).unwrap();
    h.await.unwrap();

    assert_eq!(*calls.lock().unwrap(), vec![0, 1, 2]);
    assert_eq!(ptask(&pool, ai).await.get::<String, _>("status"), "success");
    assert_eq!(queue.status(ai).await.unwrap().unwrap().retries, 2);
    let r = queue.status(af).await.unwrap().unwrap();
    assert_eq!((r.status, r.retries), (TaskStatus::Failure, 2));
    assert_eq!(r.error.unwrap()["error_type"], "SearchIndexLockError");
    let r = ptask(&pool, tl).await;
    assert_eq!(r.get::<String, _>("status"), "failure");
    assert_eq!(r.get::<Value, _>("result_data"), json!({"error_type": "TimeLimitExceeded", "error_message": "TimeLimitExceeded(0.3,)"}));
    let r = ptask(&pool, fl).await;
    assert_eq!(r.get::<Value, _>("result_data"), json!({"error_type": "ValueError", "error_message": "boom"}));
    assert!(r.get::<Option<f64>, _>("duration_seconds").is_some());
    let r = ptask(&pool, ex).await;
    assert_eq!(r.get::<String, _>("status"), "revoked");
    assert_eq!(r.get::<Value, _>("result_data"), json!({"reason": "Task expired before execution. Check worker logs for details."}));
    assert!(r.get::<Option<chrono::DateTime<chrono::Utc>>, _>("date_started").is_none());
    let r = ptask(&pool, rv).await;
    assert_eq!(r.get::<Value, _>("result_data"), json!({"reason": "Task revoked before completion. Check worker logs for details."}));
    let r = ptask(&pool, term).await;
    assert_eq!(r.get::<String, _>("status"), "revoked");
    assert_eq!(r.get::<Value, _>("result_data"), json!({"reason": "Task terminated during execution. Check worker logs for details."}));
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn chords_links_and_errbacks() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let got: Calls = Arc::default();
    let rec = |name: &'static str, g: Calls| {
        move |ctx: TaskContext| {
            let g = g.clone();
            async move {
                g.lock().unwrap().push((name.to_string(), ctx.args.clone()));
                Ok(Value::String("OK".into()))
            }
        }
    };
    let handlers = Handlers::new()
        .register("test.part", |ctx: TaskContext| async move {
            let i = ctx.kwargs.get("i").and_then(Value::as_i64).unwrap_or(0);
            if i < 0 { Err(TaskError::fail("ValueError", format!("bad {i}"))) } else { Ok(json!(i * 10)) }
        })
        .register("test.body", rec("body", got.clone()))
        .register("test.errback", rec("errback", got.clone()))
        .register("test.after", rec("after", got.clone()));
    let mut q_opts = Signature::default().options;
    q_opts.queue = Some(q.clone());
    let sig = |task: &str, k: Value| Signature { options: q_opts.clone(), ..Signature::new(task, kw(k)) };

    // Chord ok: body gets [[0, 10, 20]]
    queue
        .enqueue_chord(
            (0..3).map(|i| sig("test.part", json!({"i": i}))).collect(),
            sig("test.body", json!({})),
            Some(sig("test.errback", json!({}))),
        )
        .await
        .unwrap();
    // Chord with 1 failure: errback per header failure + once ChordError, body does not run
    queue
        .enqueue_chord(
            vec![sig("test.part", json!({"i": 1})), sig("test.part", json!({"i": -1}))],
            sig("test.body", json!({"x": 1})),
            Some(sig("test.errback", json!({"rule_id": 9}))),
        )
        .await
        .unwrap();
    // link (mutable) and link_error
    let mut o = opts(&q);
    o.link = vec![sig("test.after", json!({}))];
    queue.enqueue("test.part", kw(json!({"i": 4})), o).await.unwrap();
    let mut o = opts(&q);
    o.link_error = vec![Signature { immutable: true, ..sig("test.errback", json!({})) }];
    queue.enqueue("test.part", kw(json!({"i": -4})), o).await.unwrap();

    let (stop, h) = start(&pool, handlers, cfg(&q, &[("PAPERLESS_TASK_WORKERS", "3")]));
    let g2 = got.clone();
    wait_for("callbacks", 20, || {
        let g = g2.clone();
        async move { g.lock().unwrap().len() >= 5 }
    })
    .await;
    tokio::time::sleep(Duration::from_millis(500)).await;
    stop.send(true).unwrap();
    h.await.unwrap();
    let got = got.lock().unwrap().clone();
    let bodies: Vec<_> = got.iter().filter(|(n, _)| n == "body").collect();
    assert_eq!(bodies.len(), 1, "{got:?}");
    assert_eq!(bodies[0].1, vec![json!([0, 10, 20])]);
    let after: Vec<_> = got.iter().filter(|(n, _)| n == "after").collect();
    assert_eq!(after.len(), 1);
    assert_eq!(after[0].1, vec![json!(40)]);
    let errbacks: Vec<_> = got.iter().filter(|(n, _)| n == "errback").collect();
    // 1× header failure, 1× ChordError, 1× link_error (immutable → no arguments)
    assert_eq!(errbacks.len(), 3, "{got:?}");
    assert!(errbacks.iter().any(|(_, a)| a.len() == 3 && a[1]["exc_type"] == "ValueError" && a[1]["exc_message"] == "bad -1"));
    assert!(errbacks.iter().any(|(_, a)| a.len() == 3 && a[1]["exc_type"] == "ChordError"));
    assert!(errbacks.iter().any(|(_, a)| a.is_empty()));
}

async fn fence_token(pool: &PgPool, id: Uuid) -> i64 {
    sqlx::query("SELECT fence_token FROM paperrust_task_queue WHERE task_id = $1")
        .bind(id.to_string())
        .fetch_one(pool)
        .await
        .unwrap()
        .get("fence_token")
}

/// TLA+ finding F2: `mark_started` of a delivery that lost its lease (paused between claim and
/// start while another worker took over and finished) must not write anything and must report
/// `Lost`, so the handler does not run. A delivery whose row was only put back (not claimed anew)
/// takes it back like a heartbeat.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn stale_mark_started_is_a_noop() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let id = queue.enqueue("documents.tasks.train_classifier", Map::new(), opts(&q)).await.unwrap();
    // A claims and pauses for longer than its lease.
    let a = queue.claim("paused", std::slice::from_ref(&q), None, 10, 0.3).await.unwrap();
    assert_eq!(a.len(), 1);
    tokio::time::sleep(Duration::from_millis(400)).await;
    queue.reap_expired_leases().await.unwrap();
    assert_eq!(queue_state(&pool, id).await, "queued");
    // B takes over and finishes.
    let b = queue.claim("healthy", std::slice::from_ref(&q), None, 10, 5.0).await.unwrap();
    assert_eq!(b.len(), 1);
    assert_eq!(queue.mark_started(&b[0], 5.0).await.unwrap(), Heartbeat::Ok);
    assert!(queue.complete(&b[0], Value::String("Training completed successfully".into())).await.unwrap());
    assert_eq!(ptask(&pool, id).await.get::<String, _>("status"), "success");
    // A wakes up: fenced mark_started is a no-op.
    assert_eq!(queue.mark_started(&a[0], 5.0).await.unwrap(), Heartbeat::Lost);
    assert_eq!(ptask(&pool, id).await.get::<String, _>("status"), "success", "stale mark_started overwrote the result");
    assert_eq!(queue_state(&pool, id).await, "done");

    // Put back but not claimed anew: the original delivery may still start (takes the row back).
    let id2 = queue.enqueue("documents.tasks.train_classifier", Map::new(), opts(&q)).await.unwrap();
    let c = queue.claim("slow-start", std::slice::from_ref(&q), None, 10, 0.3).await.unwrap();
    assert_eq!(c.len(), 1);
    tokio::time::sleep(Duration::from_millis(400)).await;
    queue.reap_expired_leases().await.unwrap();
    assert_eq!(queue_state(&pool, id2).await, "queued");
    assert_eq!(queue.mark_started(&c[0], 5.0).await.unwrap(), Heartbeat::Ok);
    assert_eq!(queue_state(&pool, id2).await, "running");
    assert_eq!(ptask(&pool, id2).await.get::<String, _>("status"), "started");
    assert_eq!(queue.claim("other", std::slice::from_ref(&q), None, 10, 5.0).await.unwrap().len(), 0);
    assert!(queue.complete(&c[0], Value::Null).await.unwrap());

    // revoke(terminate=True) between claim and start: mark_started reports Terminate.
    let id3 = queue.enqueue("documents.tasks.train_classifier", Map::new(), opts(&q)).await.unwrap();
    let d = queue.claim("w", std::slice::from_ref(&q), None, 10, 5.0).await.unwrap();
    assert!(queue.revoke(id3, true).await.unwrap());
    assert_eq!(queue.mark_started(&d[0], 5.0).await.unwrap(), Heartbeat::Terminate);
}

/// TLA+ finding F3: inside ONE process (same `locked_by`) the pair (attempts, locked_by) repeats
/// after a retry; the per-delivery `fence_token` must still reject a late complete() of the old
/// delivery, so the newer delivery (with ids appended by coalescing meanwhile) is not discarded.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn old_delivery_rejected_after_reclaim_in_same_process() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let me = "paperrust@box:4242";
    let id = queue.enqueue("documents.tasks.bulk_update_documents", kw(json!({"document_ids": [1]})), opts(&q)).await.unwrap();
    let t0 = fence_token(&pool, id).await;
    // Delivery 1: finishes its handler, but its complete() is delayed past lease expiry.
    let a1 = queue.claim(me, std::slice::from_ref(&q), None, 10, 0.3).await.unwrap().remove(0);
    assert_eq!(a1.fence_token, t0 + 1);
    tokio::time::sleep(Duration::from_millis(400)).await;
    queue.reap_expired_leases().await.unwrap();
    assert_eq!(queue_state(&pool, id).await, "queued");
    // Delivery 2 (same process name) claims and asks for a retry.
    let a2 = queue.claim(me, std::slice::from_ref(&q), None, 10, 5.0).await.unwrap().remove(0);
    assert_eq!((a2.attempts, a2.fence_token), (2, t0 + 2));
    assert!(queue.retry(&a2, 0.0, &pl_queue::Failure::new("Retry", "again")).await.unwrap());
    assert_eq!(fence_token(&pool, id).await, t0 + 3, "retry must end the delivery's token");
    // Coalescing appends ids to the waiting task (same condition as pl-documents-write MERGE_SQL).
    let n = sqlx::query(
        "UPDATE paperrust_task_queue SET kwargs = jsonb_set(kwargs, '{document_ids}', (kwargs -> 'document_ids') || '[2]'::jsonb) \
         WHERE task_id = $1 AND state = 'queued' AND attempts = 0",
    )
    .bind(id.to_string())
    .execute(&pool)
    .await
    .unwrap()
    .rows_affected();
    assert_eq!(n, 1);
    // Delivery 3: same (attempts, locked_by) as delivery 1 - the old fence could not tell them apart.
    let a3 = queue.claim(me, std::slice::from_ref(&q), None, 10, 5.0).await.unwrap().remove(0);
    assert_eq!((a3.attempts, a3.locked_by.as_str()), (a1.attempts, a1.locked_by.as_str()));
    assert_eq!(a3.fence_token, t0 + 4);
    assert_eq!(a3.kwargs["document_ids"], json!([1, 2]));
    assert_eq!(queue.mark_started(&a3, 5.0).await.unwrap(), Heartbeat::Ok);
    // Delivery 1's late calls are all rejected.
    assert!(!queue.complete(&a1, json!({"stale": true})).await.unwrap(), "old delivery's complete accepted");
    assert!(!queue.fail(&a1, &pl_queue::Failure::new("X", "stale")).await.unwrap());
    assert!(!queue.retry(&a1, 0.0, &pl_queue::Failure::new("X", "stale")).await.unwrap());
    assert!(!queue.release(&a1).await.unwrap());
    assert_eq!(queue.heartbeat(&a1, 5.0).await.unwrap(), Heartbeat::Lost);
    assert_eq!(queue.mark_started(&a1, 5.0).await.unwrap(), Heartbeat::Lost);
    assert_eq!(queue.heartbeat(&a2, 5.0).await.unwrap(), Heartbeat::Lost);
    assert_eq!(queue_state(&pool, id).await, "running");
    // Delivery 3 completes normally.
    assert!(queue.complete(&a3, Value::Null).await.unwrap());
    assert_eq!(queue_state(&pool, id).await, "done");

    // release: the token moves on as well, so a late heartbeat of the released delivery cannot take
    // the queued row back; the next claim gets a fresh token.
    let id2 = queue.enqueue("documents.tasks.bulk_update_documents", kw(json!({"document_ids": [3]})), opts(&q)).await.unwrap();
    let r1 = queue.claim(me, std::slice::from_ref(&q), None, 10, 5.0).await.unwrap().remove(0);
    assert!(queue.release(&r1).await.unwrap());
    assert_eq!(queue_state(&pool, id2).await, "queued");
    assert_eq!(queue.heartbeat(&r1, 5.0).await.unwrap(), Heartbeat::Lost);
    assert_eq!(queue_state(&pool, id2).await, "queued");
    let r2 = queue.claim(me, std::slice::from_ref(&q), None, 10, 5.0).await.unwrap().remove(0);
    assert_eq!(r2.attempts, r1.attempts, "release does not count as a delivery");
    assert_eq!(r2.fence_token, r1.fence_token + 2);
    assert!(!queue.complete(&r1, Value::Null).await.unwrap());
    assert!(queue.complete(&r2, Value::Null).await.unwrap());
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn graceful_shutdown_releases_running_task() {
    let pool = pool().await;
    let q = qname();
    let queue = PgQueue::new(pool.clone(), 3);
    let id = queue.enqueue("test.long", Map::new(), opts(&q)).await.unwrap();
    let short = queue.enqueue("test.short", Map::new(), opts(&q)).await.unwrap();
    let handlers = Handlers::new()
        .register("test.long", |_c: TaskContext| async {
            tokio::time::sleep(Duration::from_secs(60)).await;
            Ok(Value::Null)
        })
        .register("test.short", |_c: TaskContext| async {
            tokio::time::sleep(Duration::from_millis(300)).await;
            Ok(Value::Null)
        });
    let (stop, h) = start(&pool, handlers, cfg(&q, &[("PAPERRUST_QUEUE_SHUTDOWN_GRACE", "1")]));
    let p = pool.clone();
    wait_for("both running", 10, || {
        let p = p.clone();
        async move { queue_state(&p, id).await == "running" && queue_state(&p, short).await == "running" }
    })
    .await;
    stop.send(true).unwrap();
    tokio::time::timeout(Duration::from_secs(10), h).await.expect("shutdown hangs").unwrap();
    // short job was allowed to finish, long one was released
    assert_eq!(queue_state(&pool, short).await, "done");
    assert_eq!(queue_state(&pool, id).await, "queued");
    let attempts: i32 = sqlx::query("SELECT attempts FROM paperrust_task_queue WHERE task_id = $1")
        .bind(id.to_string())
        .fetch_one(&pool)
        .await
        .unwrap()
        .get("attempts");
    assert_eq!(attempts, 0);
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_TEST_DATABASE_URL (own test database)"]
async fn beat_reserves_each_slot_once_across_processes() {
    let pool = pool().await;
    let store = PgBeatStore::new(pool.clone());
    let entry = BeatEntry {
        name: format!("test entry {}", Uuid::new_v4()),
        task: "documents.tasks.train_classifier".into(),
        schedule: Crontab::from_paperless("5 */1 * * *").unwrap(),
        expires: 3540.0,
        headers: Map::new(),
    };
    let tz: chrono_tz::Tz = "Europe/Zurich".parse().unwrap();
    let t = |s: &str| chrono::DateTime::parse_from_rfc3339(s).unwrap().with_timezone(&chrono::Utc);
    assert!(!store.reserve(&entry, t("2024-01-01T10:00:00Z"), tz).await.unwrap().0);
    // 8 "processes" check for the due time at the same time
    let mut handles = Vec::new();
    for _ in 0..8 {
        let s = store.clone();
        let e = entry.clone();
        handles.push(tokio::spawn(async move { s.reserve(&e, t("2024-01-01T10:05:01Z"), tz).await.unwrap().0 }));
    }
    let mut due = 0;
    for h in handles {
        if h.await.unwrap() {
            due += 1;
        }
    }
    assert_eq!(due, 1);
    sqlx::query("DELETE FROM paperrust_beat_state WHERE name = $1").bind(&entry.name).execute(&pool).await.unwrap();
}
