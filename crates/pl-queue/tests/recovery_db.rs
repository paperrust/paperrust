//! Worker loop with a missing/broken queue table (E2E finding 2026-11-08:
//! ~1000 error lines/s after the DB was recreated under the running server).
//!
//! Own file = own test process, because the test drops the table `paperrust_task_queue`
//! (it would disturb parallel tests in `db.rs`). Only against a **dedicated** database:
//! ```text
//! CREATE DATABASE pl_w18_queue TEMPLATE paperless_snapshot OWNER paperless;   (127.0.0.1:54329)
//! PAPERRUST_QUEUE_RECOVERY_DATABASE_URL=postgres://paperless:paperless@127.0.0.1:54329/pl_w18_queue \
//!   cargo test -p pl-queue -j 1 --test recovery_db -- --ignored
//! ```

use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::Duration;

use pl_core::config::Env;
use pl_queue::{EnqueueOptions, Handlers, PgQueue, QueueConfig, TaskContext, TaskQueue, Worker};
use serde_json::{Map, Value};
use sqlx::Row;
use tokio::sync::watch;
use tracing_subscriber::layer::SubscriberExt;

/// Counts ERROR events of `pl_queue::worker`.
struct CountErrors(Arc<AtomicUsize>);

impl<S: tracing::Subscriber> tracing_subscriber::Layer<S> for CountErrors {
    fn on_event(&self, e: &tracing::Event<'_>, _: tracing_subscriber::layer::Context<'_, S>) {
        if *e.metadata().level() == tracing::Level::ERROR && e.metadata().target() == "pl_queue::worker" {
            self.0.fetch_add(1, Ordering::SeqCst);
        }
    }
}

const PAPERLESSTASK_DDL: &str = "CREATE TABLE IF NOT EXISTS documents_paperlesstask (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id integer,
    task_id varchar(72) NOT NULL UNIQUE, task_type varchar(50) NOT NULL,
    trigger_source varchar(50) NOT NULL, status varchar(30) NOT NULL,
    date_created timestamptz NOT NULL, date_started timestamptz, date_done timestamptz,
    duration_seconds double precision, wait_time_seconds double precision,
    input_data jsonb NOT NULL, result_data jsonb, acknowledged boolean NOT NULL)";

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
#[ignore = "needs PAPERRUST_QUEUE_RECOVERY_DATABASE_URL (own database, table gets dropped)"]
async fn worker_backs_off_and_recreates_missing_table() {
    let url = std::env::var("PAPERRUST_QUEUE_RECOVERY_DATABASE_URL").expect("PAPERRUST_QUEUE_RECOVERY_DATABASE_URL");
    let db = url.trim_end_matches('/').rsplit('/').next().unwrap_or_default().to_owned();
    assert!(db.starts_with("pl_w18_") || db.starts_with("pl_queue_test"), "refusing to run against {db}");
    let errors = Arc::new(AtomicUsize::new(0));
    tracing::subscriber::set_global_default(tracing_subscriber::registry().with(CountErrors(errors.clone()))).unwrap();

    let pool = sqlx::postgres::PgPoolOptions::new().max_connections(5).connect(&url).await.unwrap();
    // Remove the remainder of an aborted run (view instead of table).
    sqlx::raw_sql("DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_class WHERE relname = 'paperrust_task_queue' AND relkind = 'v') THEN DROP VIEW paperrust_task_queue; END IF; END $$")
        .execute(&pool)
        .await
        .unwrap();
    sqlx::raw_sql(PAPERLESSTASK_DDL).execute(&pool).await.unwrap();
    pl_queue::migrations::apply(&pool).await.unwrap();

    let queue = format!("w18-{}", uuid::Uuid::new_v4().simple());
    let cfg = QueueConfig::from_env(&Env::from_pairs([
        ("PAPERRUST_QUEUE_BACKEND".to_string(), "postgres".to_string()),
        ("PAPERRUST_QUEUE_NAMES".to_string(), queue.clone()),
        ("PAPERRUST_QUEUE_POLL_INTERVAL".to_string(), "0.05".to_string()),
    ]))
    .unwrap();
    let ran = Arc::new(AtomicUsize::new(0));
    let r2 = ran.clone();
    let handlers = Handlers::new().register("w18.echo", move |_ctx: TaskContext| {
        let r = r2.clone();
        async move {
            r.fetch_add(1, Ordering::SeqCst);
            Ok(Value::Null)
        }
    });
    let pg = PgQueue::new(pool.clone(), cfg.max_deliveries);
    let (stop_tx, stop_rx) = watch::channel(false);
    let worker = tokio::spawn(Worker::new(pg.clone(), handlers, cfg, Default::default()).run(stop_rx));
    tokio::time::sleep(Duration::from_millis(500)).await;
    assert_eq!(errors.load(Ordering::SeqCst), 0);

    // 1. Continuous failure that is not a missing table (view without the columns → 42703):
    //    backoff 0.5 → 1 → 2 → 4 s, so at most ~5 lines in 6 s (before: thousands).
    sqlx::raw_sql("DROP TABLE paperrust_task_queue CASCADE; CREATE VIEW paperrust_task_queue AS SELECT 1::bigint AS id")
        .execute(&pool)
        .await
        .unwrap();
    tokio::time::sleep(Duration::from_secs(6)).await;
    let n = errors.load(Ordering::SeqCst);
    eprintln!("error lines in 6 s: {n}");
    assert!((1..=6).contains(&n), "error lines in 6 s: {n}");

    // 2. Table missing (42P01) → worker applies migration 0001 again and keeps working.
    sqlx::raw_sql("DROP VIEW paperrust_task_queue").execute(&pool).await.unwrap();
    let end = tokio::time::Instant::now() + Duration::from_secs(40);
    loop {
        let exists: bool =
            sqlx::query("SELECT to_regclass('paperrust_task_queue') IS NOT NULL AS e").fetch_one(&pool).await.unwrap().get("e");
        if exists {
            break;
        }
        assert!(tokio::time::Instant::now() < end, "table was not re-created");
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    let opts = EnqueueOptions { queue: Some(queue.clone()), ..Default::default() };
    pg.enqueue("w18.echo", Map::new(), opts).await.unwrap();
    let end = tokio::time::Instant::now() + Duration::from_secs(40);
    while ran.load(Ordering::SeqCst) == 0 {
        assert!(tokio::time::Instant::now() < end, "job did not run after recovery");
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    // 3. LISTEN connection terminated by the server (like DROP DATABASE … WITH (FORCE)): the worker builds
    //    a new listener after backoff (sqlx does not reconnect on its own then).
    let listeners = |pool: sqlx::PgPool| async move {
        sqlx::query("SELECT pid FROM pg_stat_activity WHERE datname = current_database() AND query ILIKE 'LISTEN%paperrust_task_queue%'")
            .fetch_all(&pool)
            .await
            .unwrap()
            .iter()
            .map(|r| r.get::<i32, _>("pid"))
            .collect::<Vec<i32>>()
    };
    let old = listeners(pool.clone()).await;
    assert!(!old.is_empty(), "worker has no LISTEN connection");
    for pid in &old {
        sqlx::query("SELECT pg_terminate_backend($1)").bind(pid).execute(&pool).await.unwrap();
    }
    let end = tokio::time::Instant::now() + Duration::from_secs(40);
    loop {
        let now = listeners(pool.clone()).await;
        if now.iter().any(|p| !old.contains(p)) {
            break;
        }
        assert!(tokio::time::Instant::now() < end, "LISTEN was not re-established");
        tokio::time::sleep(Duration::from_millis(200)).await;
    }
    let total = errors.load(Ordering::SeqCst);
    assert!(total <= n + 2, "errors after recovery: {total} (before: {n})");

    stop_tx.send(true).unwrap();
    worker.await.unwrap();
}
