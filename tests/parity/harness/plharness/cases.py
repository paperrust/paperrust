"""Case catalogue.

Files: ``tests/parity/<crate>/cases*.json`` (and ``cases*.yaml``/``.yml`` if PyYAML is
importable). ``cases.base.json`` files are generated by ``gen_base_catalog.py`` (harness
owner, do not edit by hand); crate owners add their own ``cases.json`` next to them.

File format::

    {
      "crate": "pl-objects",
      "vars": {                                   # optional, resolved once against A
        "tag_id": {"get": "/api/tags/", "query": {"ordering": "id", "page_size": 1},
                   "user": "admin", "json": "results.0.id"}
      },
      "defaults": {"users": ["admin"], "api_versions": ["10"]},   # optional
      "cases": [
        {
          "id": "tags.list.ordering-name",        # unique per catalogue
          "route": "tags.list",                   # route id (routes.toml), for the report
          "method": "GET", "path": "/api/tags/",
          "query": {"page": 1, "page_size": 25, "ordering": "name"},
          "json": null,                           # JSON request body
          "form": null,                           # form body
          "headers": {},                          # extra request headers
          "users": ["admin", "user1", "anon"],    # matrix (see users.py for references)
          "api_versions": ["10", "9"],            # "10" | "9" | "none" | any string (invalid)
          "write": false,                         # true -> snapshot reset around A and B
          "compare": "full",                      # full | status | status+headers | json-only
          "compare_headers": null,                # override header whitelist
          "expect_status": [200],                 # sanity check against A (catalogue warning)
          "leak_allow": [],                       # categories allowed (see leaks.py)
          "follow": false,                        # follow redirects
          "steps": null,                          # optional list of request dicts (same keys
                                                  #  as above + "capture": {"name": "json.path"})
                                                  #  or {"sql": "select ..."}: DB state check,
                                                  #  rows as JSON (needs PARITY_SQL_DB, see runner)
          "requires": [],                         # extra var names that must resolve
          "skip": null                            # string reason -> case skipped
        }
      ]
    }

Strings may contain ``${var}``; a string that is exactly ``${var}`` is replaced by the raw
value (keeps ints as ints). Unresolved vars skip the case with a reason.
"""

from __future__ import annotations

import copy
import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

VAR_RE = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}")
REQUEST_KEYS = {
    "method", "path", "query", "json", "form", "headers", "follow", "capture", "compare",
    "compare_headers", "expect_status", "leak_allow", "csrf", "data", "content_type",
}
CASE_KEYS = REQUEST_KEYS | {
    "id", "route", "users", "api_versions", "write", "steps", "requires", "skip", "note", "tags",
}


@dataclass
class Case:
    id: str
    crate: str
    source: str
    raw: dict
    user: str = "admin"
    api_version: str = "10"
    base_id: str = ""

    @property
    def route(self) -> str:
        return self.raw.get("route", "")

    @property
    def write(self) -> bool:
        return bool(self.raw.get("write"))

    def steps(self) -> list[dict]:
        if self.raw.get("steps"):
            out = []
            for s in self.raw["steps"]:
                st = {k: v for k, v in self.raw.items() if k in REQUEST_KEYS and k != "capture"}
                st.update(s)
                out.append(st)
            return out
        return [{k: v for k, v in self.raw.items() if k in REQUEST_KEYS}]


@dataclass
class Catalog:
    cases: list[Case] = field(default_factory=list)
    vars: dict[str, dict] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)
    files: list[str] = field(default_factory=list)


def _load_file(p: Path) -> dict | None:
    text = p.read_text(encoding="utf-8")
    if p.suffix == ".json":
        return json.loads(text)
    try:
        import yaml  # type: ignore
    except ImportError:
        return None
    return yaml.safe_load(text)


def load(parity_dir: Path, crates: list[str] | None = None) -> Catalog:
    cat = Catalog()
    files: list[Path] = []
    for pattern in ("*/cases*.json", "*/cases*.yaml", "*/cases*.yml"):
        files.extend(parity_dir.glob(pattern))
    seen_ids: set[str] = set()
    for p in sorted(files):
        if p.parent.name == "harness":
            continue
        if crates and p.parent.name not in crates:
            continue
        try:
            data = _load_file(p)
        except (OSError, ValueError) as e:
            cat.errors.append(f"{p}: {e}")
            continue
        if data is None:
            cat.errors.append(f"{p}: YAML catalogue but PyYAML not installed (skipped)")
            continue
        cat.files.append(str(p))
        crate = data.get("crate", p.parent.name)
        for name, spec in (data.get("vars") or {}).items():
            if name in cat.vars and cat.vars[name] != spec:
                cat.errors.append(f"{p}: var {name!r} redefined differently (first wins)")
                continue
            cat.vars.setdefault(name, spec)
        defaults = data.get("defaults") or {}
        for i, raw in enumerate(data.get("cases", [])):
            where = f"{p}#cases[{i}]"
            if "id" not in raw:
                cat.errors.append(f"{where}: missing id")
                continue
            unknown = set(raw) - CASE_KEYS
            if unknown:
                cat.errors.append(f"{where}: unknown keys {sorted(unknown)}")
            if raw["id"] in seen_ids:
                cat.errors.append(f"{where}: duplicate id {raw['id']!r}")
                continue
            if "path" not in raw and not raw.get("steps"):
                cat.errors.append(f"{where}: needs path or steps")
                continue
            seen_ids.add(raw["id"])
            merged = dict(defaults)
            merged.update(raw)
            users = merged.get("users") or ["admin"]
            versions = merged.get("api_versions") or ["10"]
            for u in users:
                for v in versions:
                    cid = f"{raw['id']}@{u}/v{v}"
                    cat.cases.append(
                        Case(id=cid, crate=crate, source=str(p), raw=merged, user=u,
                             api_version=str(v), base_id=raw["id"])
                    )
    return cat


def vars_in(obj: Any) -> set[str]:
    out: set[str] = set()
    if isinstance(obj, str):
        out.update(VAR_RE.findall(obj))
    elif isinstance(obj, dict):
        for k, v in obj.items():
            out |= vars_in(k)
            out |= vars_in(v)
    elif isinstance(obj, list):
        for v in obj:
            out |= vars_in(v)
    return out


class Unresolved(KeyError):
    pass


def substitute(obj: Any, values: dict[str, Any]) -> Any:
    if isinstance(obj, str):
        m = VAR_RE.fullmatch(obj)
        if m:
            if m.group(1) not in values:
                raise Unresolved(m.group(1))
            return values[m.group(1)]

        def rep(mm: re.Match) -> str:
            if mm.group(1) not in values:
                raise Unresolved(mm.group(1))
            return str(values[mm.group(1)])

        return VAR_RE.sub(rep, obj)
    if isinstance(obj, dict):
        return {substitute(k, values): substitute(v, values) for k, v in obj.items()}
    if isinstance(obj, list):
        return [substitute(v, values) for v in obj]
    return copy.copy(obj)


def json_path(doc: Any, path: str) -> Any:
    """Tiny path language: ``results.0.id``, ``0``, ``$`` (whole doc), ``len(results)``."""
    if path in ("", "$"):
        return doc
    m = re.fullmatch(r"len\((.*)\)", path)
    if m:
        return len(json_path(doc, m.group(1)))
    cur = doc
    for part in path.split("."):
        if isinstance(cur, list):
            cur = cur[int(part)]
        elif isinstance(cur, dict):
            cur = cur[part]
        else:
            raise KeyError(path)
    return cur
