"""Golden vectors for crates/pl-core/src/pyjson.rs (DRF JSONParser error texts).

Run with the reference venv (CPython 3.12, C scanner):
    reference/venv/Scripts/python.exe -I tests/parity/pl-core/pyjson_vectors.py
Writes crates/pl-core/src/pyjson_vectors.in (a Rust array literal of (input, Option<msg>)).
"""
import json
from pathlib import Path

from rest_framework.utils.json import strict_constant  # noqa: F401  (same as DRF)

INPUTS = [
    "", " ", "{", "}", "[", "]", "{bad", "{\"a\"", "{\"a\" 1}", "{\"a\":}", "{\"a\":1", "{\"a\":1,}", "{\"a\":1 \"b\":2}",
    "{,}", "[1,]", "[1 2]", "[,", "[1", "nul", "null", "true ", "tru", "falsey", "1.", "1.5x", "-", "-x", "01", "1e", "1e+",
    "1e5", "1E-2]", "\"abc", "\"a\\qb\"", "\"\\u12\"", "\"\\u12G4\"", "\"\\u1234", "\"\\u1234\"", "\"\\ud800\\u12\"",
    "\"\\ud800\\udc00\"", "\"\\ud800\\uZZZZx\"", "\"a\tb\"", "\"\\\"", "{\"a\":\"x\n", "NaN", "Infinity", "-Infinity",
    "[NaN]", "{\"a\": -Infinity}", "Nan", "\ufeff{}", "{}\n\n x", "\n\n  {\"a\": [1, 2,\n  ]}", "[\"ä\", ö]",
    "{\"k\": 1}  ", "[[[[]]]", "{\"a\":{\"b\":[}}", "'single'", "{'a': 1}", "{\"a\":1}}", "[] []", "\u00e4", "\"ok\"",
    "{\"a\": tru}", "{\"a\" : 1 , \"b\" : }", "[1,\n2,\n,3]", "\r\n{x", "123abc", "-0.5e-3", "[-]", "{\"\\x\": 1}",
]


def py_error(s):
    try:
        json.loads(s, parse_constant=strict_constant)
    except ValueError as e:
        return str(e)
    return None


def rust_str(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) > 0x7e:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


lines = ["// generated by tests/parity/pl-core/pyjson_vectors.py (CPython json + DRF strict_constant)", "["]
for s in INPUTS:
    e = py_error(s)
    lines.append(f"    ({rust_str(s)}, {'None' if e is None else 'Some(' + rust_str(e) + ')'}),")
lines.append("]")
out = Path(__file__).resolve().parents[3] / "crates" / "pl-core" / "src" / "pyjson_vectors.in"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(out, len(INPUTS))
