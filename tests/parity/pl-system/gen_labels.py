"""Generate crates/pl-system/src/labels_generated.rs from upstream/src/locale/*/django.po.

Only the PaperlessTask choice labels (TaskType, TriggerSource, Status) are extracted.
Fuzzy entries and empty translations are skipped (msgfmt does the same), entries with a
msgctxt are ignored (the model labels have none).

Run from the repository root:  python -I tests/parity/pl-system/gen_labels.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LOCALE = ROOT / "upstream" / "src" / "locale"
OUT = ROOT / "crates" / "pl-system" / "src" / "labels_generated.rs"

# upstream/src/paperless/settings/__init__.py LANGUAGES (order kept)
LANGUAGES = [
    "en-us", "ar-ar", "af-za", "be-by", "bg-bg", "ca-es", "cs-cz", "da-dk", "de-de", "el-gr",
    "en-gb", "es-es", "fa-ir", "fi-fi", "fr-fr", "hu-hu", "id-id", "it-it", "ja-jp", "ko-kr",
    "lb-lu", "no-no", "nl-nl", "pl-pl", "pt-br", "pt-pt", "ro-ro", "ru-ru", "sk-sk", "sl-si",
    "sr-cs", "sv-se", "tr-tr", "uk-ua", "vi-vn", "zh-cn", "zh-tw",
]

# upstream/src/documents/models.py PaperlessTask choices (English msgids)
MSGIDS = [
    "Pending", "Started", "Success", "Failure", "Revoked",
    "Consume File", "Train Classifier", "Sanity Check", "Index Optimize", "Mail Fetch",
    "LLM Index", "Empty Trash", "Check Workflows", "Bulk Update", "Reprocess Document",
    "Build Share Link", "Bulk Delete", "Apply AI Suggestions",
    "Scheduled", "Web UI", "API Upload", "Folder Consume", "Email Consume", "System", "Manual",
]


def to_locale(language: str) -> str:
    """django.utils.translation.to_locale"""
    lang, _, country = language.lower().partition("-")
    if not country:
        return language[:3].lower() + language[3:]
    country, _, tail = country.partition("-")
    country = country.title() if len(country) > 2 else country.upper()
    if tail:
        country += "-" + tail
    return lang + "_" + country


def unquote(s: str) -> str:
    s = s.strip()
    assert s.startswith('"') and s.endswith('"'), s
    body = s[1:-1]
    return re.sub(r'\\(.)', lambda m: {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}.get(m.group(1), m.group(1)), body)


def parse_po(path: Path) -> dict[str, str]:
    entries: dict[str, str] = {}
    fuzzy = False
    ctxt = None
    msgid = None
    msgstr = None
    cur = None

    def flush() -> None:
        nonlocal fuzzy, ctxt, msgid, msgstr, cur
        if msgid is not None and msgstr is not None and ctxt is None and not fuzzy and msgstr:
            entries[msgid] = msgstr
        fuzzy, ctxt, msgid, msgstr, cur = False, None, None, None, None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line:
            flush()
            continue
        if line.startswith("#,"):
            if msgid is not None:
                flush()
            fuzzy = "fuzzy" in line
            continue
        if line.startswith("#"):
            continue
        if line.startswith("msgctxt "):
            if msgid is not None:
                flush()
            ctxt = unquote(line[8:])
            cur = "ctxt"
        elif line.startswith("msgid "):
            if msgid is not None:
                f = fuzzy
                c = ctxt
                flush()
                fuzzy, ctxt = f, c
            msgid = unquote(line[6:])
            cur = "id"
        elif line.startswith("msgstr "):
            msgstr = unquote(line[7:])
            cur = "str"
        elif line.startswith('"'):
            part = unquote(line)
            if cur == "id":
                msgid = (msgid or "") + part
            elif cur == "str":
                msgstr = (msgstr or "") + part
            elif cur == "ctxt":
                ctxt = (ctxt or "") + part
    flush()
    return entries


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> int:
    rows = []
    for lang in LANGUAGES:
        po = LOCALE / to_locale(lang) / "LC_MESSAGES" / "django.po"
        if not po.is_file():
            continue
        cat = parse_po(po)
        for mid in MSGIDS:
            tr = cat.get(mid)
            if tr and tr != mid:
                rows.append((lang, mid, tr))
    out = [
        "// @generated by tests/parity/pl-system/gen_labels.py from upstream/src/locale (v3.4.2).",
        "// Do not edit by hand.",
        "",
        "/// (language code as in settings.LANGUAGES, English msgid, translation)",
        "pub(crate) static TRANSLATIONS: &[(&str, &str, &str)] = &[",
    ]
    for lang, mid, tr in rows:
        out.append(f"    ({rust_str(lang)}, {rust_str(mid)}, {rust_str(tr)}),")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} translations to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
