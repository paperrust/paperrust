"""Generate crates/pl-system/src/migrations_generated.rs from upstream migrations.

Lists the migrations of the paperless apps in INSTALLED_APPS order (paperless, documents,
paperless_mail) with their `replaces` (squash) lists, for `/api/status/`
(`MigrationLoader(...).graph.nodes`). Files are parsed with `ast`, never imported.

Run from the repository root:  python -I tests/parity/pl-system/gen_migrations.py
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "upstream" / "src"
OUT = ROOT / "crates" / "pl-system" / "src" / "migrations_generated.rs"
APPS = ["paperless", "documents", "paperless_mail"]


def replaces_of(path: Path) -> list[tuple[str, str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "Migration":
            for stmt in node.body:
                if isinstance(stmt, ast.Assign) and any(
                    isinstance(t, ast.Name) and t.id == "replaces" for t in stmt.targets
                ):
                    return [tuple(e) for e in ast.literal_eval(stmt.value)]
    return []


def main() -> int:
    lines = [
        "// @generated by tests/parity/pl-system/gen_migrations.py from upstream (v3.4.2). Do not edit.",
        "",
        "/// (app_label, name, replaces) in INSTALLED_APPS order, names sorted.",
        "pub(crate) static MIGRATIONS: &[(&str, &str, &[(&str, &str)])] = &[",
    ]
    for app in APPS:
        mdir = SRC / app / "migrations"
        for f in sorted(p for p in mdir.glob("*.py") if p.name != "__init__.py"):
            reps = replaces_of(f)
            reps_rs = ", ".join(f'("{a}", "{n}")' for a, n in reps)
            lines.append(f'    ("{app}", "{f.stem}", &[{reps_rs}]),')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
